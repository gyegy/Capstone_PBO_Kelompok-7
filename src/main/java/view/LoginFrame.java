    // Alur: input username & password -> cek ke tabel PENGGUNA
    // (aktif + password cocok) -> simpan sesi -> buka menu sesuai peran.
    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());

        if (username.isEmpty() || password.isEmpty()) {
            lblError.setText("Username dan password wajib diisi");
            return;
        }

        try {
            Pengguna pengguna = controller.login(username, password);

            if (pengguna == null) {
                lblError.setText("Login gagal: username/password salah atau akun nonaktif");
                txtPassword.setText("");
                return;
            }

            controller.simpanSesi(pengguna);
            bukaMenu(pengguna.getPeran());
        } catch (Exception e) {
            lblError.setText("Tidak dapat terhubung ke database");
        }
    }

    private void btnKeluarActionPerformed(java.awt.event.ActionEvent evt) {
        int pilih = javax.swing.JOptionPane.showConfirmDialog(this,
                "Apakah ingin keluar?", "Keluar",
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (pilih == javax.swing.JOptionPane.YES_OPTION) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Terima kasih telah menggunakan sistem ini");
            System.exit(0);
        }
    }

    private void bukaMenu(String peran) {
        if ("Admin".equals(peran)) {
            new AdminMenuFrame().setVisible(true);
        } else if ("Supervisor".equals(peran)) {
            new DashboardSupervisor().setVisible(true);
        } else {
            new DashboardPetugas().setVisible(true);
        }
        dispose();
    }

