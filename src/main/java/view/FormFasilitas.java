    private final Fasilitas dataAwal;
    private Runnable aksiSelesai;
    private boolean siap;

    public void setAksiSelesai(Runnable aksiSelesai) {
        this.aksiSelesai = aksiSelesai;
    }

    private void siapkanForm() {
        for (javax.swing.JComboBox<String> combo
                : new javax.swing.JComboBox[]{cmbJenis, cmbKondisi}) {
            view.util.UiKit.siapkanCombo(combo);
        }
        tombolBatal.addActionListener(e -> selesai());
        tombolSimpan.addActionListener(e -> simpan());

        if (dataAwal == null) {
            lblJudul.setText("Tambah Fasilitas");
            lblSubJudul.setText("Isi data fasilitas bandara");
            tombolSimpan.setText("Simpan Fasilitas");
        } else {
            lblJudul.setText("Ubah Data Fasilitas");
            lblSubJudul.setText("ID fasilitas: "
                    + view.util.FormatUi.idFasilitas(
                            dataAwal.getIdFasilitas()));
            tombolSimpan.setText("Simpan Perubahan");
            txtNama.setText(dataAwal.getNamaFasilitas());
            cmbJenis.setSelectedItem(dataAwal.getJenisFasilitas());
            txtLokasi.setText(dataAwal.getLokasi());
            cmbKondisi.setSelectedItem(dataAwal.getKondisi());
            txtKeterangan.setText(dataAwal.getKeterangan());
        }
        siap = true;
    }

    private void simpan() {
        if (!siap) {
            return;
        }
        String nama = txtNama.getText().trim();
        String lokasi = txtLokasi.getText().trim();
        if (nama.isEmpty() || lokasi.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Nama fasilitas dan lokasi wajib diisi.", "Periksa Isian",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        Fasilitas f = new Fasilitas();
        if (dataAwal != null) {
            f.setIdFasilitas(dataAwal.getIdFasilitas());
        } else {
            f.setAdminIdPengguna(Session.id());
        }
        f.setNamaFasilitas(nama);
        f.setJenisFasilitas(String.valueOf(cmbJenis.getSelectedItem()));
        f.setLokasi(lokasi);
        f.setKondisi(String.valueOf(cmbKondisi.getSelectedItem()));
        f.setKeterangan(txtKeterangan.getText().trim());

        FasilitasDAO dao = new FasilitasDAO();
        boolean berhasil = dataAwal == null
                ? dao.tambahFasilitas(f) : dao.updateFasilitas(f);

        if (!berhasil) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Data fasilitas gagal disimpan.", "Gagal",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this,
                dataAwal == null
                        ? "Fasilitas baru berhasil ditambahkan."
                        : "Data fasilitas berhasil diperbarui.",
                "Tersimpan", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        selesai();
    }

    private void selesai() {
        if (aksiSelesai != null) {
            aksiSelesai.run();
            return;
        }
        java.awt.Window jendela
                = javax.swing.SwingUtilities.getWindowAncestor(this);
        if (jendela instanceof MainFrame) {
            ((MainFrame) jendela).kembali();
        }
    }

