    @Override
    public void muatData() {
        if (!siap) {
            siap = true;
            siapkanTabel();
        }
        if (tugas == null) {
            muatRiwayatSaya();
        } else {
            muatRiwayatTugas();
        }
    }

    private void muatRiwayatSaya() {
        Map<Integer, String[]> fasilitasPerId = new HashMap<>();
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            fasilitasPerId.put(f.getIdFasilitas(), new String[]{
                f.getNamaFasilitas(),
                f.getLokasi() == null ? "-" : f.getLokasi()});
        }
        Map<Integer, LaporanKerusakan> laporanPerId = new HashMap<>();
        for (LaporanKerusakan l
                : new dao.LaporanKerusakanDAO().getAllLaporan()) {
            laporanPerId.put(l.getIdLaporan(), l);
        }

        java.util.Set<Integer> laporanSaya = new java.util.HashSet<>();
        for (Map.Entry<Integer, List<Integer>> entri
                : new dao.PenugasanDAO().getPetugasIdPerLaporan()
                        .entrySet()) {
            if (entri.getValue().contains(view.util.Session.id())) {
                laporanSaya.add(entri.getKey());
            }
        }

        List<ProgresPenanganan> daftar = new ArrayList<>();
        List<String> namaTugas = new ArrayList<>();
        List<String> namaFasilitas = new ArrayList<>();

        for (Penugasan p : new dao.PenugasanDAO().getAllPenugasan()) {
            if (!laporanSaya.contains(p.getLaporanIdLaporan())) {
                continue;
            }
            LaporanKerusakan laporan = laporanPerId.get(
                    p.getLaporanIdLaporan());
            String[] f = laporan == null ? new String[]{"-", "-"}
                    : fasilitasPerId.getOrDefault(
                            laporan.getFasilitasIdFasilitas(),
                            new String[]{"-", "-"});
            for (ProgresPenanganan progres
                    : new dao.ProgresPenangananDAO()
                            .getAllProgres(p.getIdPenugasan())) {
                daftar.add(progres);
                namaTugas.add(view.util.FormatUi.idTugas(
                        p.getIdPenugasan()));
                namaFasilitas.add(f[0]);
            }
        }

        Collections.reverse(daftar);
        Collections.reverse(namaTugas);
        Collections.reverse(namaFasilitas);

        modelRiwayat.setData(daftar);
        modelRiwayat.setPendamping(namaTugas, namaFasilitas);

        lblCatatan.setText(daftar.isEmpty()
                ? "Belum ada progres yang Anda catat"
                : "Menampilkan " + daftar.size()
                  + " progres  -  diurutkan dari yang terbaru");
    }

    private void muatRiwayatTugas() {
        Map<Integer, String[]> fasilitasPerId = new HashMap<>();
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            fasilitasPerId.put(f.getIdFasilitas(), new String[]{
                f.getNamaFasilitas(),
                f.getLokasi() == null ? "-" : f.getLokasi()});
        }
        Map<Integer, LaporanKerusakan> laporanPerId = new HashMap<>();
        for (LaporanKerusakan l
                : new dao.LaporanKerusakanDAO().getAllLaporan()) {
            laporanPerId.put(l.getIdLaporan(), l);
        }

        LaporanKerusakan laporan = laporanPerId.get(
                tugas.getLaporanIdLaporan());
        String[] f = laporan == null ? new String[]{"-", "-"}
                : fasilitasPerId.getOrDefault(
                        laporan.getFasilitasIdFasilitas(),
                        new String[]{"-", "-"});

        List<String> nama = new dao.PenugasanDAO()
                .getNamaPetugasPerPenugasan()
                .getOrDefault(tugas.getIdPenugasan(), new ArrayList<>());

        lblJudul.setText("Riwayat Progres Penugasan "
                + view.util.FormatUi.idTugas(tugas.getIdPenugasan()));
        lblSubJudul.setText(f[0] + "  -  "
                + (nama.isEmpty() ? "belum ada petugas"
                        : String.join(", ", nama)));

        List<ProgresPenanganan> daftar = new dao.ProgresPenangananDAO()
                .getAllProgres(tugas.getIdPenugasan());
        modelTugas.setData(daftar);
        modelTugas.setPendamping(null, null);

        lblCatatan.setText(daftar.isEmpty()
                ? "Belum ada progres pada penugasan ini"
                : "Menampilkan " + daftar.size()
                  + " progres penanganan  -  diurutkan dari yang terbaru");
    }

