    private void siapkanTabel() {
        tabelTugas.setModel(modelTabel);
        view.util.UiKit.siapkanTabel(tabelTugas);
        tabelTugas.setRowHeight(48);

        int[] lebar = {100, 130, 190, 190, 130, 150, 120};
        for (int i = 0; i < lebar.length; i++) {
            tabelTugas.getColumnModel().getColumn(i)
                    .setPreferredWidth(lebar[i]);
        }
        tabelTugas.getColumnModel().getColumn(0)
                .setCellRenderer(new RendererTabel.Id());
        tabelTugas.getColumnModel().getColumn(1)
                .setCellRenderer(new RendererTabel.TeksRedup());
        tabelTugas.getColumnModel().getColumn(2)
                .setCellRenderer(new RendererTabel.Teks());
        tabelTugas.getColumnModel().getColumn(3)
                .setCellRenderer(new RendererTabel.Utama());
        tabelTugas.getColumnModel().getColumn(4)
                .setCellRenderer(new RendererTabel.Lencana());
        tabelTugas.getColumnModel().getColumn(5)
                .setCellRenderer(new RendererTabel.Lencana());
        tabelTugas.getColumnModel().getColumn(6)
                .setCellRenderer(new RendererTabel.AksiDinamis());

        tabelTugas.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent e) {
                int baris = tabelTugas.rowAtPoint(e.getPoint());
                int kolom = tabelTugas.columnAtPoint(e.getPoint());
                if (baris < 0 || baris >= modelTabel.getRowCount()) {
                    return;
                }
                if (kolom == modelTabel.getColumnCount() - 1) {
                    bukaRiwayat(modelTabel.get(baris));
                }
            }
        });
    }

    @Override
    public String judul() {
        return "Pantau Progres";
    }

    @Override
    public void muatData() {
        if (!siap) {
            siap = true;
            siapkanTabel();
        }

        Map<Integer, String[]> fasilitasPerId = new HashMap<>();
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            fasilitasPerId.put(f.getIdFasilitas(), new String[]{
                f.getNamaFasilitas(),
                f.getLokasi() == null ? "-" : f.getLokasi()});
        }
        Map<Integer, LaporanKerusakan> laporanPerId = new HashMap<>();
        for (LaporanKerusakan l
                : new dao.LaporanKerusakanDAO().getAllLaporan()) {
            laporanPerId.put(l.getIdLaporan(), l);
        }
        Map<Integer, List<String>> petugasPerTugas
                = new dao.PenugasanDAO().getNamaPetugasPerPenugasan();

        daftarTugas.clear();
        List<String> fasilitas = new ArrayList<>();
        List<String> lokasi = new ArrayList<>();
        List<String> petugas = new ArrayList<>();
        List<String> prioritas = new ArrayList<>();
        List<String> statusLaporan = new ArrayList<>();
        List<String> progresTerakhir = new ArrayList<>();

        for (Penugasan p : new dao.PenugasanDAO().getAllPenugasan()) {
            daftarTugas.add(p);
            LaporanKerusakan laporan = laporanPerId.get(
                    p.getLaporanIdLaporan());
            String[] f = laporan == null ? new String[]{"-", "-"}
                    : fasilitasPerId.getOrDefault(
                            laporan.getFasilitasIdFasilitas(),
                            new String[]{"-", "-"});
            fasilitas.add(f[0]);
            lokasi.add(f[1]);
            petugas.add(gabung(petugasPerTugas.get(p.getIdPenugasan())));
            prioritas.add(laporan == null ? "-" : laporan.getPrioritas());
            statusLaporan.add(laporan == null ? "-" : laporan.getStatus());

            List<ProgresPenanganan> progres = new dao.ProgresPenangananDAO()
                    .getAllProgres(p.getIdPenugasan());
            progresTerakhir.add(progres.isEmpty() ? "-"
                    : progres.get(progres.size() - 1).getStatusProgres());
        }

        modelTabel.setData(daftarTugas);
        modelTabel.setPendamping(fasilitas, lokasi, petugas, prioritas);
        modelTabel.setStatusPendamping(statusLaporan, progresTerakhir);

        lblCatatan.setText(daftarTugas.isEmpty()
                ? "Belum ada penugasan tercatat"
                : "Menampilkan " + daftarTugas.size()
                  + " penugasan  -  klik Lihat Riwayat untuk rinciannya");
    }

    private String gabung(List<String> nama) {
        if (nama == null || nama.isEmpty()) {
            return "-";
        }
        return String.join(", ", nama);
    }

    private void bukaRiwayat(Penugasan tugas) {
        java.awt.Window jendela
                = javax.swing.SwingUtilities.getWindowAncestor(this);
        if (jendela instanceof MainFrame) {
            ((MainFrame) jendela).bukaForm(
                    "Riwayat " + view.util.FormatUi.idTugas(
                            tugas.getIdPenugasan()),
                    new RiwayatProgresView(tugas));
        }
    }

