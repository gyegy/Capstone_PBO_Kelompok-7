    // CREATE
    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {
        FasilitasDialog dialog = new FasilitasDialog(this, true, null);
        dialog.setVisible(true);

        if (dialog.isBerhasil()) {
            muatData(txtCari.getText());
        }
    }

    // UPDATE
    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {
        Fasilitas f = fasilitasTerpilih();
        if (f == null) {
            return;
        }

        FasilitasDialog dialog = new FasilitasDialog(this, true, f);
        dialog.setVisible(true);

        if (dialog.isBerhasil()) {
            muatData(txtCari.getText());
        }
    }

    // DELETE: tidak boleh jika fasilitas sudah punya riwayat laporan kerusakan
    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {
        Fasilitas f = fasilitasTerpilih();
        if (f == null) {
            return;
        }

        for (LaporanKerusakan l : new LaporanKerusakanDAO().getAllLaporan()) {
            if (l.getFasilitasIdFasilitas() == f.getIdFasilitas()) {
                JOptionPane.showMessageDialog(this,
                        "Fasilitas tidak dapat dihapus (memiliki riwayat laporan)",
                        "Fasilitas tidak dapat dihapus",
                        JOptionPane.WARNING_MESSAGE);
                return;
            }
        }

        int pilih = JOptionPane.showConfirmDialog(this,
                "Hapus fasilitas " + f.getNamaFasilitas() + "?",
                "Konfirmasi", JOptionPane.YES_NO_OPTION);

        if (pilih != JOptionPane.YES_OPTION) {
            return;
        }

        if (fasilitasDAO.hapusFasilitas(f.getIdFasilitas())) {
            JOptionPane.showMessageDialog(this, "Fasilitas berhasil dihapus");
            muatData(txtCari.getText());
        } else {
            JOptionPane.showMessageDialog(this,
                    "Fasilitas gagal dihapus",
                    "Kesalahan", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {
        new AdminMenuFrame().setVisible(true);
        dispose();
    }


