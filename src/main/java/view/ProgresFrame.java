    // READ: tugas aktif Petugas login
    private void muatData(int idTugasPilih) {
        int idPetugas = Integer.parseInt(Sesi.getIdPengguna());
        daftar = ViewUtil.penugasanPetugas(idPetugas, true);
        Map<Integer, LaporanKerusakan> laporan = ViewUtil.petaLaporan();

        DefaultTableModel model = (DefaultTableModel) tblTugas.getModel();
        model.setRowCount(0);

        for (int i = 0; i < daftar.size(); i++) {
            Penugasan p = daftar.get(i);
            LaporanKerusakan l = laporan.get(p.getLaporanIdLaporan());
            Fasilitas f = l == null ? null : petaFasilitas.get(l.getFasilitasIdFasilitas());
            model.addRow(new Object[] {
                ViewUtil.idTugas(p.getIdPenugasan()),
                f == null ? "-" : f.getNamaFasilitas(),
                l == null ? "-" : l.getPrioritas(),
                p.getCatatanPenugasan() == null ? "-" : p.getCatatanPenugasan()
            });
            if (p.getIdPenugasan() == idTugasPilih) {
                tblTugas.setRowSelectionInterval(i, i);
            }
        }

        lblInfo.setText(daftar.isEmpty()
                ? "Tidak ada tugas aktif"
                : "Menampilkan " + daftar.size() + " tugas aktif");
    }

    // Teks bawaan jika Petugas tidak mengisi tindakan (kolom opsional di alur,
    // tetapi wajib terisi di DAO)
    private String tindakanBawaan(String status) {
        switch (status) {
            case "Pemeriksaan":
                return "Pemeriksaan awal dan pencatatan kondisi";
            case "Perbaikan":
                return "Perbaikan komponen atau penggantian bagian rusak";
            case "Pengujian":
                return "Uji fungsi setelah perbaikan";
            default:
                return "Pemeriksaan akhir dan dokumentasi hasil";
        }
    }

    // CREATE: simpan progres (DAO memperbarui status laporan / kondisi fasilitas)
    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {
        int baris = tblTugas.getSelectedRow();

        if (baris < 0 || baris >= daftar.size()) {
            JOptionPane.showMessageDialog(this,
                    "Pilih tugas pada tabel terlebih dahulu",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        if (cmbStatus.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Status progres wajib dipilih",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String status = (String) cmbStatus.getSelectedItem();
        String tindakan = txtTindakan.getText().trim();

        if (tindakan.length() > 150) {
            JOptionPane.showMessageDialog(this,
                    "Tindakan penanganan melebihi batas 150 karakter",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (tindakan.isEmpty()) {
            tindakan = tindakanBawaan(status);
        }

        Penugasan tugas = daftar.get(baris);

        ProgresPenanganan progres = new ProgresPenanganan();
        progres.setWaktuUpdate(new Timestamp(System.currentTimeMillis()));
        progres.setStatusProgres(status);
        progres.setTindakanPenanganan(tindakan);
        progres.setPenugasanIdPenugasan(tugas.getIdPenugasan());

        if (!progresDAO.tambahProgres(progres)) {
            JOptionPane.showMessageDialog(this,
                    "Progres gagal disimpan",
                    "Kesalahan", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if ("Selesai".equals(status)) {
            JOptionPane.showMessageDialog(this,
                    "Progres dicatat, penugasan selesai.\nLaporan "
                    + ViewUtil.idLaporan(tugas.getLaporanIdLaporan())
                    + " kini berstatus Selesai dan kondisi fasilitas menjadi Baik.");
        } else {
            JOptionPane.showMessageDialog(this, "Progres berhasil dicatat");
        }

        cmbStatus.setSelectedIndex(0);
        txtTindakan.setText("");
        muatData(0);
    }

