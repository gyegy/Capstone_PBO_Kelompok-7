    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {
        boolean catat = (dataLama == null);

        int indeks = cmbFasilitas.getSelectedIndex();
        String deskripsi = txtDeskripsi.getText().trim();
        boolean prioritasDipilih = cmbPrioritas.getSelectedIndex() > 0;

        // validasi: deskripsi terisi (maks. 150), prioritas & fasilitas dipilih
        if (indeks <= 0 || deskripsi.isEmpty() || !prioritasDipilih) {
            peringatan("Data laporan belum lengkap");
            return;
        }
        if (deskripsi.length() > 150) {
            peringatan("Deskripsi melebihi batas 150 karakter");
            return;
        }

        Fasilitas fasilitas = daftarFasilitas.get(indeks - 1);
        String prioritas = (String) cmbPrioritas.getSelectedItem();
        int idAdmin = Integer.parseInt(Sesi.getIdPengguna());

        LaporanKerusakan laporan = new LaporanKerusakan();
        laporan.setDeskripsiKerusakan(deskripsi);
        laporan.setPrioritas(prioritas);
        laporan.setFasilitasIdFasilitas(fasilitas.getIdFasilitas());

        if (catat) {
            // id otomatis (auto increment), tanggal = hari ini,
            // status = Menunggu (diatur DAO), ADMIN = admin login
            laporan.setTanggalLaporan(java.sql.Date.valueOf(LocalDate.now()));
            laporan.setAdminIdPengguna(idAdmin);

            if (!laporanDAO.tambahLaporan(laporan)) {
                JOptionPane.showMessageDialog(this,
                        "Laporan gagal disimpan. Periksa koneksi database.",
                        "Kesalahan", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // kondisi fasilitas otomatis menjadi Rusak
            fasilitas.setKondisi("Rusak");
            fasilitasDAO.updateFasilitas(fasilitas);

            JOptionPane.showMessageDialog(this,
                    "Laporan berhasil dicatat" + cariIdBaru(idAdmin, fasilitas, deskripsi));
        } else {
            laporan.setIdLaporan(dataLama.getIdLaporan());
            laporan.setTanggalLaporan(dataLama.getTanggalLaporan());
            laporan.setAdminIdPengguna(dataLama.getAdminIdPengguna());

            if (!laporanDAO.updateLaporan(laporan)) {
                JOptionPane.showMessageDialog(this,
                        "Laporan gagal diperbarui. Laporan hanya dapat diubah selama berstatus Menunggu dan belum ditugaskan.",
                        "Kesalahan", JOptionPane.ERROR_MESSAGE);
                return;
            }
            JOptionPane.showMessageDialog(this, "Laporan berhasil diperbarui");
        }

        berhasil = true;
        dispose();
    }

    // ID laporan baru = laporan terbaru milik admin ini untuk fasilitas tsb
    private String cariIdBaru(int idAdmin, Fasilitas fasilitas, String deskripsi) {
        for (LaporanKerusakan l : laporanDAO.getAllLaporan()) {
            if (l.getAdminIdPengguna() == idAdmin
                    && l.getFasilitasIdFasilitas() == fasilitas.getIdFasilitas()
                    && deskripsi.equals(l.getDeskripsiKerusakan())) {
                return " (ID laporan: L-" + String.format("%04d", l.getIdLaporan()) + ")";
            }
        }
        return "";
    }


