    // Baca tabel FASILITAS (nama, jenis, lokasi, kondisi) untuk dipilih
    private void muatFasilitas() {
        daftarFasilitas = fasilitasDAO.getAllFasilitas();

        for (Fasilitas f : daftarFasilitas) {
            cmbFasilitas.addItem(f.getNamaFasilitas() + " - " + f.getLokasi()
                    + " (" + f.getJenisFasilitas() + ", " + f.getKondisi() + ")");
        }
    }

    private void pilihFasilitas(int idFasilitas) {
        for (int i = 0; i < daftarFasilitas.size(); i++) {
            if (daftarFasilitas.get(i).getIdFasilitas() == idFasilitas) {
                cmbFasilitas.setSelectedIndex(i + 1);
                return;
            }
        }
    }

