    private void siapkanForm() {
        view.util.UiKit.siapkanTabel(tabelPilih);
        tabelPilih.setModel(modelFasilitas);
        tabelPilih.setRowHeight(56);

        RendererTabel.Pilih rendererPilih
                = new RendererTabel.Pilih(false, view.util.Theme.ADMIN);
        rendererPilih.setTerpilih(modelFasilitas::dipilih);
        tabelPilih.getColumnModel().getColumn(0).setMaxWidth(52);
        tabelPilih.getColumnModel().getColumn(0).setMinWidth(52);
        tabelPilih.getColumnModel().getColumn(0)
                .setCellRenderer(rendererPilih);
        tabelPilih.getColumnModel().getColumn(1)
                .setCellRenderer(new RendererTabel.Utama());
        tabelPilih.getColumnModel().getColumn(2)
                .setCellRenderer(new RendererTabel.TeksRedup());
        tabelPilih.getColumnModel().getColumn(3)
                .setCellRenderer(new RendererTabel.TeksRedup());
        tabelPilih.getColumnModel().getColumn(4)
                .setCellRenderer(new RendererTabel.Lencana());

        int[] lebar = {52, 180, 120, 130, 100};
        for (int i = 0; i < lebar.length; i++) {
            tabelPilih.getColumnModel().getColumn(i)
                    .setPreferredWidth(lebar[i]);
        }

        tabelPilih.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent e) {
                int baris = tabelPilih.rowAtPoint(e.getPoint());
                if (baris < 0 || baris >= modelFasilitas.getRowCount()) {
                    return;
                }
                modelFasilitas.pilih(baris);
                tabelPilih.repaint();
            }
        });

        ChipPilihan.hubungkan(chipTinggi, chipSedang, chipRendah);

        txtDeskripsi.getDocument().addDocumentListener(
                new javax.swing.event.DocumentListener() {
            @Override
            public void insertUpdate(javax.swing.event.DocumentEvent e) {
                perbaruiHitung();
            }

            @Override
            public void removeUpdate(javax.swing.event.DocumentEvent e) {
                perbaruiHitung();
            }

            @Override
            public void changedUpdate(javax.swing.event.DocumentEvent e) {
                perbaruiHitung();
            }
        });

        tombolBatal.addActionListener(e -> selesai());
        tombolSimpan.addActionListener(e -> simpan());

        terapkanMode();
        siap = true;
    }

    /** Menampilkan susunan isian sesuai mode tambah atau ubah. */
    private void terapkanMode() {
        boolean ubah = dataAwal != null;
        panelPilih.setVisible(!ubah);
        panelInfo.setVisible(ubah);
        lblJudulDetail.setText(ubah ? "Isi Perbaikan Laporan"
                : "2. Detail Kerusakan");

        if (ubah) {
            lblJudul.setText("Ubah Laporan");
            lblSubJudul.setText(FormatUi.idLaporan(dataAwal.getIdLaporan())
                    + "     -     status " + dataAwal.getStatus());
            txtIdLaporan.setText(FormatUi.idLaporan(
                    dataAwal.getIdLaporan()));
            txtIdLaporan.setEnabled(false);
            txtFasilitas.setEnabled(false);
            txtDeskripsi.setText(dataAwal.getDeskripsiKerusakan());
            pilihPrioritas(dataAwal.getPrioritas());
            tombolSimpan.setText("Simpan Perubahan");
        } else {
            pilihPrioritas("Sedang");
            perbaruiHitung();
        }
    }

    private void pilihPrioritas(String prioritas) {
        chipTinggi.setAktif("Tinggi".equals(prioritas));
        chipSedang.setAktif("Sedang".equals(prioritas));
        chipRendah.setAktif("Rendah".equals(prioritas));
    }

    private void perbaruiHitung() {
        int jumlah = txtDeskripsi.getText().length();
        lblHitung.setText(jumlah + " / " + BATAS_DESKRIPSI + " karakter");
        lblHitung.setForeground(jumlah > BATAS_DESKRIPSI
                ? view.util.Theme.RED : view.util.Theme.TEXT_FAINT);
    }

    @Override
    public String judul() {
        return dataAwal == null ? "Catat Laporan" : "Ubah Laporan";
    }

    @Override
    public void muatData() {
        if (dataAwal != null) {
            return;
        }

        daftarFasilitas.clear();
        List<Object[]> isi = new ArrayList<>();
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            daftarFasilitas.add(f);
            isi.add(new Object[]{f.getNamaFasilitas(), f.getJenisFasilitas(),
                f.getLokasi(), f.getKondisi()});
        }
        modelFasilitas.setData(daftarFasilitas, isi);
    }

    private void simpan() {
        if (!siap) {
            return;
        }

        String deskripsi = txtDeskripsi.getText().trim();
        if (deskripsi.isEmpty()) {
            pesan("Deskripsi kerusakan wajib diisi.");
            return;
        }
        if (deskripsi.length() > BATAS_DESKRIPSI) {
            pesan("Deskripsi kerusakan maksimal " + BATAS_DESKRIPSI
                    + " karakter.");
            return;
        }

        String prioritas = ChipPilihan.nilaiAktif(chipTinggi, chipSedang,
                chipRendah);
        if (prioritas.isEmpty()) {
            pesan("Tentukan prioritas kerusakan terlebih dahulu.");
            return;
        }

        LaporanKerusakan laporan = new LaporanKerusakan();
        if (dataAwal != null) {
            laporan.setIdLaporan(dataAwal.getIdLaporan());
            laporan.setTanggalLaporan(dataAwal.getTanggalLaporan());
            laporan.setAdminIdPengguna(dataAwal.getAdminIdPengguna());
            laporan.setFasilitasIdFasilitas(
                    dataAwal.getFasilitasIdFasilitas());
        } else {
            int baris = modelFasilitas.indeksTerpilih();
            if (baris < 0) {
                pesan("Pilih satu fasilitas pada daftar di sebelah kiri.");
                return;
            }
            Fasilitas fasilitas = daftarFasilitas.get(baris);
            laporan.setTanggalLaporan(
                    new java.sql.Date(System.currentTimeMillis()));
            laporan.setAdminIdPengguna(view.util.Session.id());
            laporan.setFasilitasIdFasilitas(fasilitas.getIdFasilitas());
        }
        laporan.setDeskripsiKerusakan(deskripsi);
        laporan.setPrioritas(prioritas);

        dao.LaporanKerusakanDAO dao = new dao.LaporanKerusakanDAO();
        boolean berhasil = dataAwal == null
                ? dao.tambahLaporan(laporan) : dao.updateLaporan(laporan);

        if (!berhasil) {
            pesan(dataAwal == null
                    ? "Laporan gagal disimpan. Periksa kembali isian Anda."
                    : "Laporan tidak dapat diubah karena sudah ditugaskan "
                      + "atau sudah diproses.");
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this,
                dataAwal == null
                        ? "Laporan kerusakan berhasil dicatat."
                        : "Laporan kerusakan berhasil diperbarui.",
                "Tersimpan", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        selesai();
    }

    private void pesan(String teks) {
        javax.swing.JOptionPane.showMessageDialog(this, teks, "Periksa Isian",
                javax.swing.JOptionPane.WARNING_MESSAGE);
    }

    private void selesai() {
        if (aksiSelesai != null) {
            aksiSelesai.run();
            return;
        }
        java.awt.Window jendela
                = javax.swing.SwingUtilities.getWindowAncestor(this);
        if (jendela instanceof MainFrame) {
            ((MainFrame) jendela).kembali();
        }
    }

