    private final Map<String, HalamanAeroCare> halaman = new LinkedHashMap<>();
    private final Map<String, java.awt.Component> formDinamis
            = new LinkedHashMap<>();
    private final JPanel areaKonten = new JPanel(new CardLayout());
    private String menuSaatIni;
    private String menuSebelumForm;

    private void siapkanKerangka() {
        panelKonten.add(areaKonten, BorderLayout.CENTER);

        String peran = Session.peran();
        sidebar.terapkanPeran(peran);
        header.setPengguna(Session.nama(), peran);

        sidebar.setAksiMenu(this::bukaHalaman);
        sidebar.setAksiLogout(this::konfirmasiKeluar);

        addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosing(java.awt.event.WindowEvent e) {
                konfirmasiKeluar();
            }
        });

        addComponentListener(new java.awt.event.ComponentAdapter() {
            @Override
            public void componentResized(java.awt.event.ComponentEvent e) {
                tataUlang();
            }
        });

        daftarHalaman();
        bukaHalaman("Dashboard");
    }

    private void daftarHalaman() {
        if (Session.admin()) {
            halaman.put("Dashboard", new DashboardAdmin());
            halaman.put("Kelola Pengguna", new PenggunaView());
            halaman.put("Kelola Fasilitas", new FasilitasView());
            halaman.put("Laporan Kerusakan", new LaporanView());
            halaman.put("Cari Laporan", new CariLaporanView());
        } else if (Session.supervisor()) {
            halaman.put("Dashboard", new DashboardSupervisor());
            halaman.put("Penugasan Laporan", new PenugasanView());
            halaman.put("Pantau Progres", new PantauProgresView());
            halaman.put("Cari Laporan", new CariLaporanView());
            halaman.put("Rekap Laporan", new RekapLaporanView());
        } else {
            halaman.put("Dashboard", new DashboardPetugas());
            halaman.put("Tugas Saya", new TugasSayaView());
            halaman.put("Perbarui Progres", new PerbaruiProgresView());
            halaman.put("Riwayat Progres", new RiwayatProgresView());
            halaman.put("Cari Laporan", new CariLaporanView());
        }

        areaKonten.removeAll();
        for (Map.Entry<String, HalamanAeroCare> entri : halaman.entrySet()) {
            areaKonten.add((java.awt.Component) entri.getValue(), entri.getKey());
        }
    }

    /** Membuka halaman menu utama, lalu memuat datanya. */
    public void bukaHalaman(String namaMenu) {
        HalamanAeroCare target = halaman.get(namaMenu);
        if (target == null) {
            return;
        }
        tampilkanKartu(namaMenu, target);
    }

    /**
     * Membuka form tambah/ubah sebagai halaman di dalam kerangka. Form dibuat
     * ulang setiap kali dibuka sehingga datanya selalu segar.
     */
    public void bukaForm(String kunci, java.awt.Component form) {
        if (menuSaatIni != null) {
            menuSebelumForm = menuSaatIni;
        }
        java.awt.Component lama = formDinamis.remove(kunci);
        if (lama != null) {
            areaKonten.remove(lama);
        }
        formDinamis.put(kunci, form);
        areaKonten.add(form, kunci);

        // Form tambah/ubah yang punya tombol Batal diminta kembali ke menu asal
        try {
            java.lang.reflect.Method m = form.getClass()
                    .getMethod("setAksiSelesai", Runnable.class);
            m.invoke(form, (Runnable) this::kembali);
        } catch (NoSuchMethodException | IllegalAccessException
                | java.lang.reflect.InvocationTargetException e) {
            // Form tanpa aksi selesai tidak perlu diatur.
        }

        if (form instanceof HalamanAeroCare) {
            tampilkanKartu(kunci, (HalamanAeroCare) form);
        } else {
            ((CardLayout) areaKonten.getLayout()).show(areaKonten, kunci);
            header.setJejak(kunci);
            areaKonten.revalidate();
            areaKonten.repaint();
        }
    }

    /** Kembali ke menu yang sedang aktif sebelum form tambah/ubah dibuka. */
    public void kembali() {
        String tujuan = menuSebelumForm == null ? "Dashboard" : menuSebelumForm;
        menuSebelumForm = null;
        bukaHalaman(tujuan);
    }

    private void tampilkanKartu(String kunci, HalamanAeroCare target) {
        ((CardLayout) areaKonten.getLayout()).show(areaKonten, kunci);
        if (halaman.containsKey(kunci)) {
            menuSaatIni = kunci;
        }
        sidebar.setMenuAktif(kunci);
        header.setJejak(target.judul());
        target.muatData();
        sesuaikanHalaman(target);
    }

    private void sesuaikanHalaman(HalamanAeroCare target) {
        // areaKonten harus sudah memperoleh ukuran akhirnya lebih dulu, kalau
        // tidak halaman akan menata ulang dirinya memakai lebar lama.
        panelKonten.doLayout();
        target.sesuaikanUkuran(Math.max(400, areaKonten.getWidth()),
                Math.max(300, areaKonten.getHeight()));
    }

    private void tataUlang() {
        int w = getContentPane().getWidth();
        int h = getContentPane().getHeight();
        sidebar.setBounds(0, 0, 240, h);
        header.setBounds(240, 0, Math.max(1, w - 240), 64);
        panelKonten.setBounds(240, 64, Math.max(1, w - 240), Math.max(1, h - 64));
        panelKonten.doLayout();

        for (HalamanAeroCare halamanAktif : halaman.values()) {
            sesuaikanHalaman(halamanAktif);
        }
        for (java.awt.Component form : formDinamis.values()) {
            if (form instanceof HalamanAeroCare) {
                sesuaikanHalaman((HalamanAeroCare) form);
            }
        }
    }

    private void konfirmasiKeluar() {
        DialogKeluar dialog = new DialogKeluar(this);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
    }

