    // READ: progres dari semua penugasan Petugas login, terbaru di atas
    private void muatData() {
        int idPetugas = Integer.parseInt(Sesi.getIdPengguna());
        Map<Integer, Fasilitas> fasilitas = ViewUtil.petaFasilitas();
        Map<Integer, LaporanKerusakan> laporan = ViewUtil.petaLaporan();
        ProgresPenangananDAO progresDAO = new ProgresPenangananDAO();

        List<ProgresPenanganan> urut = new ArrayList<>();
        Map<Integer, Penugasan> tugasDari = new java.util.HashMap<>();

        for (Penugasan p : ViewUtil.penugasanPetugas(idPetugas, false)) {
            for (ProgresPenanganan r : progresDAO.getAllProgres(p.getIdPenugasan())) {
                urut.add(r);
                tugasDari.put(r.getIdProgres(), p);
            }
        }

        urut.sort((a, b) -> b.getWaktuUpdate().compareTo(a.getWaktuUpdate()));

        DefaultTableModel model = (DefaultTableModel) tblRiwayat.getModel();
        model.setRowCount(0);

        for (ProgresPenanganan r : urut) {
            Penugasan p = tugasDari.get(r.getIdProgres());
            LaporanKerusakan l = laporan.get(p.getLaporanIdLaporan());
            Fasilitas f = l == null ? null : fasilitas.get(l.getFasilitasIdFasilitas());
            model.addRow(new Object[] {
                ViewUtil.idTugas(p.getIdPenugasan()),
                ViewUtil.waktu(r.getWaktuUpdate()),
                f == null ? "-" : f.getNamaFasilitas(),
                r.getStatusProgres(),
                r.getTindakanPenanganan() == null ? "-" : r.getTindakanPenanganan()
            });
        }

        lblInfo.setText(urut.isEmpty()
                ? "Belum ada riwayat progres"
                : "Menampilkan " + urut.size() + " riwayat progres");
    }

