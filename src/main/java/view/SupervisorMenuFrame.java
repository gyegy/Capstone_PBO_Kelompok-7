    private void muatRingkasan() {
        List<LaporanKerusakan> menunggu = SupervisorUtil.laporanMenungguPenugasan();
        Map<Integer, Fasilitas> fasilitas = ViewUtil.petaFasilitas();

        lblStatNilai1.setText(String.valueOf(menunggu.size()));
        lblStatKet1.setText("Laporan belum ditugaskan");

        lblStatNilai2.setText(String.valueOf(SupervisorUtil.jumlahPenugasanBerjalan()));
        lblStatKet2.setText("Sedang diproses");

        lblStatNilai3.setText(String.valueOf(SupervisorUtil.jumlahSelesaiBulanIni()));
        lblStatKet3.setText("Laporan tuntas");

        lblStatNilai4.setText(String.valueOf(SupervisorUtil.petugasAktif().size()));
        lblStatKet4.setText("Siap ditugaskan");

        DefaultTableModel model = (DefaultTableModel) tblPerlu.getModel();
        model.setRowCount(0);

        int batas = Math.min(5, menunggu.size());
        for (int i = 0; i < batas; i++) {
            LaporanKerusakan l = menunggu.get(i);
            Fasilitas f = fasilitas.get(l.getFasilitasIdFasilitas());
            model.addRow(new Object[] {
                ViewUtil.idLaporan(l.getIdLaporan()),
                f == null ? "-" : f.getNamaFasilitas(),
                f == null ? "-" : f.getLokasi(),
                l.getPrioritas()
            });
        }
    }

