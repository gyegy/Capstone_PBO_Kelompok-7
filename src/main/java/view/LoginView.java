    /**
     * Menata ulang isi jendela mengikuti ukurannya, sehingga panel kiri dan
     * kanan tetap memenuhi layar saat jendela diperbesar.
     */
    private void tataUlang() {
        int w = Math.max(1, getContentPane().getWidth());
        int h = Math.max(1, getContentPane().getHeight());
        int lebarKiri = Math.max(360, w * 40 / 100);
        int lebarKanan = w - lebarKiri;
        int lebarForm = Math.min(420, Math.max(300, lebarKanan - 120));
        int xForm = lebarKiri + (lebarKanan - lebarForm) / 2;

        panelKiri.setBounds(0, 0, lebarKiri, h);
        panelKanan.setBounds(lebarKiri, 0, lebarKanan, h);

        int yTengah = h / 2;
        int lebarTeks = Math.max(160, lebarKiri - 120);
        logo.setBounds(60, yTengah - 164, 104, 104);
        lblMerek.setBounds(60, yTengah - 24, lebarTeks, 44);
        lblDeskripsi.setBounds(60, yTengah + 26, lebarTeks, 34);
        view.util.UiKit.labelBungkus(lblDeskripsi, lebarTeks);
        lblCatatan.setBounds(60, yTengah + 68, lebarTeks, 48);
        view.util.UiKit.labelBungkus(lblCatatan, lebarTeks);

        lblJudul.setBounds(xForm, yTengah - 172, lebarForm, 32);
        lblSub.setBounds(xForm, yTengah - 138, lebarForm, 20);
        panelPesan.setBounds(xForm, yTengah - 108, lebarForm, 38);
        lblPesan.setBounds(14, 10, lebarForm - 28, 18);
        lblUsername.setBounds(xForm, yTengah - 56, 200, 16);
        txtUsername.setBounds(xForm, yTengah - 36, lebarForm, 38);
        lblPassword.setBounds(xForm, yTengah + 16, 200, 16);
        txtPassword.setBounds(xForm, yTengah + 36, lebarForm, 38);
        tombolMasuk.setBounds(xForm, yTengah + 94, lebarForm, 40);
        tombolKembali.setBounds(xForm, yTengah + 144, lebarForm, 40);
    }

    /** Memasang aksi dan menyembunyikan pesan kesalahan. */
    public void setSiap() {
        tombolMasuk.addActionListener(e -> prosesMasuk());
        tombolKembali.addActionListener(e -> kembali());
        txtPassword.addActionListener(e -> prosesMasuk());
        panelPesan.setVisible(false);
        txtUsername.requestFocusInWindow();
    }

    private void prosesMasuk() {
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());

        controller.LoginController kontrol = new controller.LoginController();
        model.Pengguna pengguna = kontrol.prosesLogin(username, password);

        if (pengguna == null) {
            lblPesan.setText("Login gagal: username/password salah atau akun nonaktif");
            panelPesan.setVisible(true);
            return;
        }

        view.util.Session.masuk(pengguna);
        MainFrame utama = new MainFrame();
        view.util.Navigasi.tutupDanBuka(this, utama);
    }

    private void kembali() {
        SplashView splash = new SplashView();
        splash.setSiap();
        view.util.Navigasi.tutupDanBuka(this, splash);
    }
