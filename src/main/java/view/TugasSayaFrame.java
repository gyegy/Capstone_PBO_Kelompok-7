    // READ: tugas aktif Petugas login (DETAIL_PENUGASAN Aktif, laporan belum Selesai)
    private void muatData() {
        int idPetugas = Integer.parseInt(Sesi.getIdPengguna());
        daftar = ViewUtil.penugasanPetugas(idPetugas, true);

        Map<Integer, Fasilitas> fasilitas = ViewUtil.petaFasilitas();
        Map<Integer, LaporanKerusakan> laporan = ViewUtil.petaLaporan();

        DefaultTableModel model = (DefaultTableModel) tblTugas.getModel();
        model.setRowCount(0);

        for (Penugasan p : daftar) {
            LaporanKerusakan l = laporan.get(p.getLaporanIdLaporan());
            Fasilitas f = l == null ? null : fasilitas.get(l.getFasilitasIdFasilitas());
            model.addRow(new Object[] {
                ViewUtil.idTugas(p.getIdPenugasan()),
                ViewUtil.idLaporan(p.getLaporanIdLaporan()),
                f == null ? "-" : f.getNamaFasilitas(),
                f == null ? "-" : f.getLokasi(),
                l == null ? "-" : l.getPrioritas(),
                p.getCatatanPenugasan() == null ? "-" : p.getCatatanPenugasan()
            });
        }

        lblInfo.setText(daftar.isEmpty()
                ? "Tidak ada tugas aktif"
                : "Menampilkan " + daftar.size() + " tugas aktif");
    }

    private void btnPerbaruiActionPerformed(java.awt.event.ActionEvent evt) {
        int baris = tblTugas.getSelectedRow();

        if (baris < 0 || baris >= daftar.size()) {
            JOptionPane.showMessageDialog(this,
                    "Pilih tugas pada tabel terlebih dahulu",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        new ProgresFrame(daftar.get(baris).getIdPenugasan()).setVisible(true);
        dispose();
    }

    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {
        new PetugasMenuFrame().setVisible(true);
        dispose();
    }


