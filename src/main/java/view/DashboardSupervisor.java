    @Override
    public void muatData() {
        if (!siap) {
            siap = true;
            siapkanTabel();
        }

        Map<Integer, LaporanKerusakan> laporanPerId = new HashMap<>();
        Map<Integer, String[]> fasilitasPerId = new HashMap<>();
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            fasilitasPerId.put(f.getIdFasilitas(), new String[]{
                f.getNamaFasilitas(),
                f.getLokasi() == null ? "-" : f.getLokasi()});
        }

        List<LaporanKerusakan> menunggu = new ArrayList<>();
        for (LaporanKerusakan l
                : new dao.LaporanKerusakanDAO().getAllLaporan()) {
            laporanPerId.put(l.getIdLaporan(), l);
            if ("Menunggu".equals(l.getStatus())) {
                menunggu.add(l);
            }
        }

        int berjalan = 0;
        int selesai = 0;
        for (LaporanKerusakan l : laporanPerId.values()) {
            if ("Selesai".equals(l.getStatus())) {
                selesai++;
            } else if ("Diproses".equals(l.getStatus())) {
                berjalan++;
            }
        }

        List<Object[]> isi = new ArrayList<>();
        for (LaporanKerusakan l : menunggu) {
            String[] fasilitas = fasilitasPerId.getOrDefault(
                    l.getFasilitasIdFasilitas(), new String[]{"-", "-"});
            isi.add(new Object[]{FormatUi.idLaporan(l.getIdLaporan()),
                fasilitas[0], fasilitas[1], l.getPrioritas()});
        }
        modelTugas.setBaris(isi);
        lblJudulTugas.setText(menunggu.isEmpty()
                ? "Perlu Ditugaskan  -  semua laporan sudah ditugaskan"
                : "Perlu Ditugaskan  -  " + menunggu.size() + " laporan");

        int petugasAktif = new dao.PenggunaDAO().getPetugasAktif().size();

        isiKartu(kartuMenunggu, "Menunggu Penugasan",
                FormatUi.angka(menunggu.size()),
                menunggu.isEmpty() ? "Semua laporan sudah ditugaskan"
                        : "Laporan belum ditugaskan",
                view.util.Theme.PETUGAS);
        isiKartu(kartuBerjalan, "Penugasan Berjalan",
                FormatUi.angka(berjalan), "Sedang diproses",
                view.util.Theme.SUPERVISOR);
        isiKartu(kartuSelesai, "Laporan Selesai",
                FormatUi.angka(selesai), "Laporan tuntas",
                view.util.Theme.GREEN);
        isiKartu(kartuPetugas, "Petugas Aktif",
                FormatUi.angka(petugasAktif), "Siap ditugaskan",
                view.util.Theme.TEXT);

        muatProgresTerbaru(fasilitasPerId, laporanPerId);
    }

    private void isiKartu(view.util.CardStatistik kartu, String judul,
            String nilai, String keterangan, java.awt.Color warna) {
        kartu.setJudul(judul);
        kartu.setNilai(nilai);
        kartu.setKeterangan(keterangan);
        kartu.setWarnaNilai(warna);
    }

    /**
     * Menyusun daftar progres terbaru sebagai baris teks di dalam kartu,
     * karena kartu kanan hanya memuat beberapa entri ringkas.
     */
    private void muatProgresTerbaru(Map<Integer, String[]> fasilitasPerId,
            Map<Integer, LaporanKerusakan> laporanPerId) {
        panelDaftarProgres.removeAll();

        List<ProgresPenanganan> ringkas = new ArrayList<>();
        Map<Integer, String> namaPerTugas = new HashMap<>();
        for (Penugasan p : new dao.PenugasanDAO().getAllPenugasan()) {
            List<ProgresPenanganan> progres = new dao.ProgresPenangananDAO()
                    .getAllProgres(p.getIdPenugasan());
            if (progres.isEmpty()) {
                continue;
            }
            ProgresPenanganan terakhir = progres.get(progres.size() - 1);
            ringkas.add(terakhir);
            namaPerTugas.put(terakhir.getIdProgres(),
                    namaFasilitas(p, fasilitasPerId, laporanPerId));
        }

        Collections.reverse(ringkas);
        if (ringkas.isEmpty()) {
            view.util.BadgeLabel kosong
                    = new view.util.BadgeLabel("Belum ada progres");
            // Lebar mengikuti teks agar tidak terpotong.
            java.awt.Dimension ukuranKosong = kosong.getPreferredSize();
            kosong.setBounds(0, 0, ukuranKosong.width, 24);
            panelDaftarProgres.add(kosong);
            panelDaftarProgres.revalidate();
            panelDaftarProgres.repaint();
            return;
        }

        int batas = Math.min(MAKS_PROGRES, ringkas.size());
        int y = 0;
        for (int i = 0; i < batas; i++) {
            ProgresPenanganan progres = ringkas.get(i);

            javax.swing.JLabel judulBaris = new javax.swing.JLabel(
                    namaPerTugas.getOrDefault(progres.getIdProgres(), "-"));
            judulBaris.setFont(view.util.Theme.bold(13f));
            judulBaris.setForeground(view.util.Theme.TEXT);
            judulBaris.setBounds(0, y, 300, 18);

            javax.swing.JLabel keterangan = new javax.swing.JLabel(
                    progres.getStatusProgres() + "  -  "
                    + FormatUi.tanggal(progres.getWaktuUpdate()));
            keterangan.setFont(view.util.Theme.regular(11.5f));
            keterangan.setForeground(view.util.Theme.TEXT_MUTED);
            keterangan.setBounds(0, y + 18, 300, 16);

            panelDaftarProgres.add(judulBaris);
            panelDaftarProgres.add(keterangan);
            y += 50;
        }
        panelDaftarProgres.revalidate();
        panelDaftarProgres.repaint();
    }

    private String namaFasilitas(Penugasan penugasan,
            Map<Integer, String[]> fasilitasPerId,
            Map<Integer, LaporanKerusakan> laporanPerId) {
        LaporanKerusakan laporan = laporanPerId.get(
                penugasan.getLaporanIdLaporan());
        if (laporan == null) {
            return "-";
        }
        return fasilitasPerId.getOrDefault(laporan.getFasilitasIdFasilitas(),
                new String[]{"-", "-"})[0];
    }

    @Override
    public void sesuaikanUkuran(int lebar, int tinggi) {
        int isi = Math.max(620, lebar - 68);
        int celah = 16;
        int lebarKartu = (isi - celah * 3) / 4;
        int x = 34;
        view.util.CardStatistik[] kartu = {kartuMenunggu, kartuBerjalan,
            kartuSelesai, kartuPetugas};
        for (view.util.CardStatistik k : kartu) {
            k.setBounds(x, 96, lebarKartu, 104);
            x += lebarKartu + celah;
        }

        int tinggiKartu = Math.max(240, tinggi - 280);
        int lebarKiri = isi * 63 / 100;
        int lebarKanan = isi - lebarKiri - celah;

        panelTugas.setBounds(34, 220, lebarKiri, tinggiKartu);
        scrollTugas.setBounds(22, 60, lebarKiri - 44, tinggiKartu - 80);
        tabelTugas.setBounds(0, 0, lebarKiri - 44, tinggiKartu - 80);
        tombolTugaskan.setBounds(lebarKiri - 140, 14, 118, 32);
        lblJudulTugas.setBounds(22, 20, lebarKiri - 180, 24);

        panelProgres.setBounds(34 + lebarKiri + celah, 220, lebarKanan,
                tinggiKartu);
        panelDaftarProgres.setBounds(22, 56, lebarKanan - 44,
                tinggiKartu - 80);
    }
