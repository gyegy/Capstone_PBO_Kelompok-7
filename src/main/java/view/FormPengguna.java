    private void siapkanForm() {
        for (javax.swing.JComboBox<String> combo
                : new javax.swing.JComboBox[]{cmbPeran, cmbKhusus1,
                    cmbKhusus2}) {
            view.util.UiKit.siapkanCombo(combo);
        }
        cmbPeran.addActionListener(e -> terapkanPeran());
        tombolBatal.addActionListener(e -> selesai());
        tombolSimpan.addActionListener(e -> simpan());

        if (dataAwal == null) {
            lblJudul.setText("Tambah Pengguna");
            lblSubJudul.setText("Isi data akun, lalu data khusus sesuai peran");
            tombolSimpan.setText("Simpan Pengguna");
        } else {
            lblJudul.setText("Ubah Data Pengguna");
            lblSubJudul.setText("ID pengguna: "
                    + view.util.FormatUi.idPengguna(dataAwal.getIdPengguna())
                    + "     -     peran tidak dapat diubah");
            tombolSimpan.setText("Simpan Perubahan");
            isiForm(dataAwal);
            cmbPeran.setEnabled(false);
        }
        terapkanPeran();
        siap = true;
    }

    private void isiForm(Pengguna p) {
        txtNama.setText(p.getNamaLengkap());
        txtUsername.setText(p.getUsername());
        txtEmail.setText(p.getEmail());
        txtTelepon.setText(p.getNoTelepon());
        if (p.getPeran() != null) {
            cmbPeran.setSelectedItem(p.getPeran());
        }
    }

