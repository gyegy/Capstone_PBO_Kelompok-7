    // Validasi periode (kosong = tanpa batas) lalu tampilkan rekap
    private void terapkan() {
        java.sql.Date dari;
        java.sql.Date sampai;

        try {
            dari = txtDari.getText().trim().isEmpty()
                    ? null : java.sql.Date.valueOf(txtDari.getText().trim());
            sampai = txtSampai.getText().trim().isEmpty()
                    ? null : java.sql.Date.valueOf(txtSampai.getText().trim());
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this,
                    "Rentang tanggal tidak valid (format yyyy-MM-dd)",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (dari != null && sampai != null && dari.after(sampai)) {
            JOptionPane.showMessageDialog(this, "Rentang tanggal tidak valid",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        tglDari = dari;
        tglSampai = sampai;

        SupervisorUtil.HasilRekap h = SupervisorUtil.hitungRekap(dari, sampai);
        Map<String, Integer> a = h.angka;

        lblMenunggu.setText("Menunggu : " + a.getOrDefault("menunggu", 0));
        lblDiproses.setText("Diproses : " + a.getOrDefault("diproses", 0));
        lblSelesai.setText("Selesai : " + a.getOrDefault("selesai", 0));
        lblTinggi.setText("Tinggi : " + a.getOrDefault("prioritasTinggi", 0));
        lblSedang.setText("Sedang : " + a.getOrDefault("prioritasSedang", 0));
        lblRendah.setText("Rendah : " + a.getOrDefault("prioritasRendah", 0));

        DefaultTableModel mBerulang = (DefaultTableModel) tblBerulang.getModel();
        mBerulang.setRowCount(0);
        daftarBerulang = h.berulang;
        for (SupervisorUtil.BarisFasilitas b : h.berulang) {
            mBerulang.addRow(new Object[] {b.nama, b.jenis, b.jumlah});
        }

        DefaultTableModel mBeban = (DefaultTableModel) tblBeban.getModel();
        mBeban.setRowCount(0);
        for (SupervisorUtil.BarisBeban b : h.beban) {
            mBeban.addRow(new Object[] {b.nama, b.penugasan, b.laporanDitangani});
        }

        if (h.rataHari < 0) {
            lblWaktuNilai.setText("-");
            lblWaktuKet.setText("Belum ada laporan Selesai pada periode ini");
        } else {
            lblWaktuNilai.setText(SupervisorUtil.formatHari(h.rataHari));
            lblWaktuKet.setText("Rata-rata " + h.jumlahSelesai
                    + " laporan: progres Selesai - tanggal laporan");
        }

        String periode = (dari == null && sampai == null) ? "Semua periode"
                : (dari == null ? "..." : dari.toString()) + " s/d "
                + (sampai == null ? "..." : sampai.toString());
        lblInfo.setText("Periode: " + periode + "  |  Total laporan: "
                + a.getOrDefault("totalLaporan", 0));
    }

    private void btnTerapkanActionPerformed(java.awt.event.ActionEvent evt) {
        terapkan();
    }

    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {
        txtDari.setText("");
        txtSampai.setText("");
        terapkan();
    }

    private void btnRiwayatActionPerformed(java.awt.event.ActionEvent evt) {
        int baris = tblBerulang.getSelectedRow();

        if (baris < 0 || baris >= daftarBerulang.size()) {
            JOptionPane.showMessageDialog(this,
                    "Pilih fasilitas pada tabel terlebih dahulu",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        new RiwayatGangguanFrame(daftarBerulang.get(baris).idFasilitas,
                tglDari, tglSampai).setVisible(true);
        dispose();
    }

    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {
        new SupervisorMenuFrame().setVisible(true);
        dispose();
    }


