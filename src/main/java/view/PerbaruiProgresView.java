    @Override
    public void muatData() {
        if (!siap) {
            siap = true;
            siapkanTabel();
        }

        Map<Integer, String[]> fasilitasPerId = new HashMap<>();
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            fasilitasPerId.put(f.getIdFasilitas(), new String[]{
                f.getNamaFasilitas(),
                f.getLokasi() == null ? "-" : f.getLokasi()});
        }
        Map<Integer, LaporanKerusakan> laporanPerId = new HashMap<>();
        for (LaporanKerusakan l
                : new dao.LaporanKerusakanDAO().getAllLaporan()) {
            laporanPerId.put(l.getIdLaporan(), l);
        }

        java.util.Set<Integer> laporanSaya = new java.util.HashSet<>();
        for (Map.Entry<Integer, List<Integer>> entri
                : new dao.PenugasanDAO().getPetugasIdPerLaporan()
                        .entrySet()) {
            if (entri.getValue().contains(view.util.Session.id())) {
                laporanSaya.add(entri.getKey());
            }
        }

        daftarTugas.clear();
        List<Object[]> isi = new ArrayList<>();
        for (Penugasan p : new dao.PenugasanDAO().getAllPenugasan()) {
            if (!laporanSaya.contains(p.getLaporanIdLaporan())) {
                continue;
            }
            LaporanKerusakan laporan = laporanPerId.get(
                    p.getLaporanIdLaporan());
            if (laporan == null || "Selesai".equals(laporan.getStatus())) {
                continue;
            }
            daftarTugas.add(p);
            String[] f = fasilitasPerId.getOrDefault(
                    laporan.getFasilitasIdFasilitas(), new String[]{"-", "-"});
            isi.add(new Object[]{FormatUi.idTugas(p.getIdPenugasan()), f[0],
                laporan.getPrioritas()});
        }
        modelTugas.setData(daftarTugas, isi);

        lblJudulTugas.setText(daftarTugas.isEmpty()
                ? "1. Pilih Tugas  -  tidak ada tugas aktif"
                : "1. Pilih Tugas  -  " + daftarTugas.size() + " tugas aktif");

        txtTindakan.setText("");
        chipPemeriksaan.setAktif(true);
        chipPerbaikan.setAktif(false);
        chipPengujian.setAktif(false);
        chipSelesai.setAktif(false);
    }

    private void simpan() {
        int baris = modelTugas.indeksTerpilih();
        if (baris < 0) {
            pesan("Pilih satu tugas terlebih dahulu.");
            return;
        }

        String status = ChipPilihan.nilaiAktif(chipPemeriksaan, chipPerbaikan,
                chipPengujian, chipSelesai);
        if (status.isEmpty()) {
            pesan("Tentukan status progres terlebih dahulu.");
            return;
        }

        ProgresPenanganan progres = new ProgresPenanganan();
        progres.setWaktuUpdate(
                new java.sql.Timestamp(System.currentTimeMillis()));
        progres.setStatusProgres(status);
        progres.setTindakanPenanganan(txtTindakan.getText().trim());
        progres.setPenugasanIdPenugasan(
                daftarTugas.get(baris).getIdPenugasan());

        if (!new dao.ProgresPenangananDAO().tambahProgres(progres)) {
            pesan("Progres gagal disimpan. Periksa kembali isian Anda.");
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this,
                "Selesai".equals(status)
                        ? "Progres dicatat, penugasan selesai. Status laporan "
                          + "dan kondisi fasilitas ikut diperbarui."
                        : "Progres berhasil dicatat.",
                "Tersimpan", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        muatData();
    }

    private void pesan(String teks) {
        javax.swing.JOptionPane.showMessageDialog(this, teks, "Periksa Isian",
                javax.swing.JOptionPane.WARNING_MESSAGE);
    }

    @Override
    public void sesuaikanUkuran(int lebar, int tinggi) {
        int isi = Math.max(620, lebar - 68);
        int celah = 16;
        int lebarKiri = isi * 55 / 100;
        int lebarKanan = isi - lebarKiri - celah;
        int xKanan = 34 + lebarKiri + celah;

        int tinggiKartu = Math.max(360, tinggi - 184);
        int tinggiTabel = tinggiKartu - 76;

        panelTugas.setBounds(34, 156, lebarKiri, tinggiKartu);
        scrollTugas.setBounds(22, 56, lebarKiri - 44, tinggiTabel);
        tabelTugas.setBounds(0, 0, lebarKiri - 44, tinggiTabel);

        panelProgres.setBounds(xKanan, 156, lebarKanan, tinggiKartu);

        int lebarChip = (lebarKanan - 44 - 3 * 8) / 4;
        chipPemeriksaan.setBounds(22, 74, lebarChip, 36);
        chipPerbaikan.setBounds(22 + lebarChip + 8, 74, lebarChip, 36);
        chipPengujian.setBounds(22 + (lebarChip + 8) * 2, 74, lebarChip, 36);
        chipSelesai.setBounds(22 + (lebarChip + 8) * 3, 74, lebarChip, 36);

        int tinggiArea = Math.max(120, tinggiKartu - 360);
        txtTindakan.setBounds(22, 148, lebarKanan - 44, tinggiArea);
        lblPeringatan.setBounds(22, 158 + tinggiArea, lebarKanan - 44, 60);
        view.util.UiKit.labelBungkus(lblPeringatan, lebarKanan - 44);
        tombolSimpan.setBounds(22, tinggiKartu - 76, lebarKanan - 44, 42);
    }
