    private final List<Penugasan> daftarTugas = new ArrayList<>();
    private boolean siap;

    private void siapkanTabel() {
        view.util.UiKit.siapkanTabel(tabelTugas);
        tabelTugas.setModel(modelTugas);
        tabelTugas.setRowHeight(52);

        RendererTabel.Pilih pilih
                = new RendererTabel.Pilih(false, view.util.Theme.PETUGAS);
        pilih.setTerpilih(modelTugas::dipilih);
        javax.swing.table.TableColumn kolom
                = tabelTugas.getColumnModel().getColumn(0);
        kolom.setMinWidth(44);
        kolom.setMaxWidth(44);
        kolom.setCellRenderer(pilih);

        tabelTugas.getColumnModel().getColumn(1)
                .setCellRenderer(new RendererTabel.Id());
        tabelTugas.getColumnModel().getColumn(2)
                .setCellRenderer(new RendererTabel.Utama());
        tabelTugas.getColumnModel().getColumn(3)
                .setCellRenderer(new RendererTabel.Lencana());

        int[] lebar = {44, 100, 240, 110};
        for (int i = 0; i < lebar.length; i++) {
            tabelTugas.getColumnModel().getColumn(i)
                    .setPreferredWidth(lebar[i]);
        }

        tabelTugas.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent e) {
                int baris = tabelTugas.rowAtPoint(e.getPoint());
                if (baris < 0 || baris >= modelTugas.getRowCount()) {
                    return;
                }
                modelTugas.pilih(baris);
                tampilkanProgresTerakhir();
            }
        });

        ChipPilihan.hubungkan(chipPemeriksaan, chipPerbaikan, chipPengujian,
                chipSelesai);
        chipPemeriksaan.setAktif(true);
        tombolSimpan.addActionListener(e -> simpan());
    }

    /** Menampilkan tindakan terakhir agar petugas tidak mencatat ulang. */
    private void tampilkanProgresTerakhir() {
        int baris = modelTugas.indeksTerpilih();
        if (baris < 0) {
            return;
        }
        Penugasan tugas = daftarTugas.get(baris);
        List<ProgresPenanganan> progres = new dao.ProgresPenangananDAO()
                .getAllProgres(tugas.getIdPenugasan());
        if (progres.isEmpty()) {
            lblPeringatan.setText("Belum ada progres untuk tugas ini. "
                    + "Catat pemeriksaan awal Anda.");
            return;
        }
        ProgresPenanganan terakhir = progres.get(progres.size() - 1);
        lblPeringatan.setText("Progres terakhir: "
                + terakhir.getStatusProgres() + "  -  "
                + FormatUi.tanggalWaktu(terakhir.getWaktuUpdate())
                + ". Memilih Selesai akan menutup penugasan ini.");
    }

