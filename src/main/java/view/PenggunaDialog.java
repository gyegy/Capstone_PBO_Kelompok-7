    // Mode Ubah: username & peran tetap, password boleh dikosongkan
    private void isiForm(Pengguna p) {
        lblJudul.setText("Ubah Data Pengguna (ID " + p.getIdPengguna() + ")");
        lblUsername.setText("Username (tetap)");
        lblPassword.setText("Password (kosongkan jika tidak diubah)");
        lblPeran.setText("Peran (tetap)");

        txtNama.setText(p.getNamaLengkap());
        txtUsername.setText(p.getUsername());
        txtUsername.setEditable(false);
        txtEmail.setText(p.getEmail() == null ? "" : p.getEmail());
        txtTelepon.setText(p.getNoTelepon());
        cmbPeran.setSelectedItem(p.getPeran());
        cmbPeran.setEnabled(false);

        if (p instanceof Admin) {
            String s = ((Admin) p).getHakAkses();
            txtHakAkses.setText(s == null ? "" : s);
        } else if (p instanceof Supervisor) {
            String s = ((Supervisor) p).getAreaPengawasan();
            txtArea.setText(s == null ? "" : s);
        } else if (p instanceof Petugas) {
            cmbSpesialisasi.setSelectedItem(((Petugas) p).getSpesialisasi());
            cmbShift.setSelectedItem(((Petugas) p).getShiftKerja());
        }
    }

