    private String kosongJadiNull(String s) {
        s = s.trim();
        return s.isEmpty() ? null : s;
    }

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {
        boolean tambah = (dataLama == null);

        String nama = txtNama.getText().trim();
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());
        String email = txtEmail.getText().trim();
        String telepon = txtTelepon.getText().trim();
        String peran = (String) cmbPeran.getSelectedItem();

        // validasi: data terisi dan sesuai batas panjang kolom
        if (nama.isEmpty() || nama.length() > 60) {
            peringatan("Data tidak lengkap atau melebihi batas: Nama lengkap wajib diisi (maks. 60 karakter)");
            return;
        }
        if (tambah && (username.isEmpty() || username.length() > 30)) {
            peringatan("Data tidak lengkap atau melebihi batas: Username wajib diisi (maks. 30 karakter)");
            return;
        }
        if (tambah && (password.length() < 6 || password.length() > 30)) {
            peringatan("Data tidak lengkap atau melebihi batas: Password 6-30 karakter");
            return;
        }
        if (!tambah && !password.isEmpty()
                && (password.length() < 6 || password.length() > 30)) {
            peringatan("Data tidak lengkap atau melebihi batas: Password baru 6-30 karakter");
            return;
        }
        if (email.length() > 50) {
            peringatan("Data tidak lengkap atau melebihi batas: Email maks. 50 karakter");
            return;
        }
        if (telepon.isEmpty() || telepon.length() > 20) {
            peringatan("Data tidak lengkap atau melebihi batas: No. telepon wajib diisi (maks. 20 karakter)");
            return;
        }

        // data khusus sesuai peran
        String data1 = null;
        String data2 = null;

        if ("Admin".equals(peran)) {
            data1 = kosongJadiNull(txtHakAkses.getText());
            if (data1 != null && data1.length() > 50) {
                peringatan("Data tidak lengkap atau melebihi batas: Hak akses maks. 50 karakter");
                return;
            }
        } else if ("Supervisor".equals(peran)) {
            data1 = kosongJadiNull(txtArea.getText());
            if (data1 != null && data1.length() > 50) {
                peringatan("Data tidak lengkap atau melebihi batas: Area pengawasan maks. 50 karakter");
                return;
            }
        } else {
            data1 = (String) cmbSpesialisasi.getSelectedItem();
            data2 = (String) cmbShift.getSelectedItem();
        }

        // username tidak boleh kembar (hanya saat Tambah)
        if (tambah) {
            for (Pengguna p : penggunaDAO.getAllPengguna()) {
                if (p.getUsername().equalsIgnoreCase(username)) {
                    peringatan("Username sudah digunakan");
                    return;
                }
            }
        }

        boolean ok;
        if (tambah) {
            ok = penggunaDAO.tambahPengguna(nama, username, password,
                    kosongJadiNull(email), telepon, peran, "Aktif",
                    data1, data2);
        } else {
            ok = penggunaDAO.updatePengguna(dataLama.getIdPengguna(), nama,
                    dataLama.getUsername(), password, kosongJadiNull(email),
                    telepon, dataLama.getStatusAktif(), data1, data2);
        }

        if (ok) {
            JOptionPane.showMessageDialog(this, tambah
                    ? "Pengguna berhasil ditambahkan"
                    : "Data pengguna berhasil diperbarui");
            berhasil = true;
            dispose();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Data pengguna gagal disimpan. Periksa koneksi database.",
                    "Kesalahan", JOptionPane.ERROR_MESSAGE);
        }
    }


