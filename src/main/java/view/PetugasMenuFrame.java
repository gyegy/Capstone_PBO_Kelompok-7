    private void muatRingkasan() {
        int idPetugas = Integer.parseInt(Sesi.getIdPengguna());

        for (Pengguna u : new PenggunaDAO().getAllPengguna()) {
            if (u.getIdPengguna() == idPetugas && u instanceof Petugas) {
                Petugas pt = (Petugas) u;
                lblSub.setText("Spesialisasi: " + pt.getSpesialisasi()
                        + "  |  Shift: " + pt.getShiftKerja());
            }
        }

        Map<Integer, LaporanKerusakan> laporan = ViewUtil.petaLaporan();
        List<Penugasan> aktif = ViewUtil.penugasanPetugas(idPetugas, true);
        int diproses = 0;
        int tinggi = 0;

        for (Penugasan p : aktif) {
            LaporanKerusakan l = laporan.get(p.getLaporanIdLaporan());
            if (l == null) {
                continue;
            }
            if ("Diproses".equals(l.getStatus())) {
                diproses++;
            }
            if ("Tinggi".equals(l.getPrioritas())) {
                tinggi++;
            }
        }

        int selesaiBulanIni = 0;
        LocalDate hariIni = LocalDate.now();
        ProgresPenangananDAO progresDAO = new ProgresPenangananDAO();

        for (Penugasan p : ViewUtil.penugasanPetugas(idPetugas, false)) {
            for (ProgresPenanganan r : progresDAO.getAllProgres(p.getIdPenugasan())) {
                if ("Selesai".equals(r.getStatusProgres()) && r.getWaktuUpdate() != null) {
                    LocalDate d = r.getWaktuUpdate().toLocalDateTime().toLocalDate();
                    if (d.getYear() == hariIni.getYear() && d.getMonth() == hariIni.getMonth()) {
                        selesaiBulanIni++;
                    }
                }
            }
        }

        lblStatNilai1.setText(String.valueOf(aktif.size()));
        lblStatKet1.setText("Belum selesai");
        lblStatNilai2.setText(String.valueOf(diproses));
        lblStatKet2.setText("Sudah ada progres");
        lblStatNilai3.setText(String.valueOf(tinggi));
        lblStatKet3.setText("Utamakan lebih dulu");
        lblStatNilai4.setText(String.valueOf(selesaiBulanIni));
        lblStatKet4.setText("Tugas tuntas");
    }

