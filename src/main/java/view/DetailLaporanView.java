    private final LaporanKerusakan laporan;
    private final ProgresTableModel modelProgres
            = new ProgresTableModel(ProgresTableModel.Mode.RIWAYAT_TUGAS);
    private boolean tabelSiap;

    private void siapkanTabel() {
        tabelProgres.setModel(modelProgres);
        view.util.UiKit.siapkanTabel(tabelProgres);
        tabelProgres.setRowHeight(48);

        int[] lebar = {180, 150, 640};
        for (int i = 0; i < lebar.length; i++) {
            tabelProgres.getColumnModel().getColumn(i)
                    .setPreferredWidth(lebar[i]);
        }
        tabelProgres.getColumnModel().getColumn(0)
                .setCellRenderer(new RendererTabel.TeksRedup());
        tabelProgres.getColumnModel().getColumn(1)
                .setCellRenderer(new RendererTabel.Lencana());
        tabelProgres.getColumnModel().getColumn(2)
                .setCellRenderer(new RendererTabel.Teks());
    }

    @Override
    public String judul() {
        return "Cari Laporan";
    }

    @Override
    public void muatData() {
        if (!tabelSiap) {
            tabelSiap = true;
            siapkanTabel();
        }
        if (laporan == null) {
            return;
        }

        lblJudul.setText("Detail Laporan "
                + FormatUi.idLaporan(laporan.getIdLaporan()));

        Fasilitas fasilitas = cariFasilitas(laporan.getFasilitasIdFasilitas());
        lblVFasilitas.setText(fasilitas == null
                ? "-" : fasilitas.getNamaFasilitas() + "  ("
                  + fasilitas.getJenisFasilitas() + ")");
        lblVLokasi.setText(fasilitas == null ? "-" : fasilitas.getLokasi());
        lblVTanggal.setText(FormatUi.tanggal(laporan.getTanggalLaporan()));
        badgePrioritas.setTeks(laporan.getPrioritas());
        badgeStatus.setTeks(laporan.getStatus());
        lblVDeskripsi.setText(laporan.getDeskripsiKerusakan() == null
                ? "-" : laporan.getDeskripsiKerusakan());

        muatPetugas();
        muatProgres();
    }

    private Fasilitas cariFasilitas(int idFasilitas) {
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            if (f.getIdFasilitas() == idFasilitas) {
                return f;
            }
        }
        return null;
    }

    private void muatPetugas() {
        Penugasan tugas = null;
        for (Penugasan p : new dao.PenugasanDAO().getAllPenugasan()) {
            if (p.getLaporanIdLaporan() == laporan.getIdLaporan()) {
                tugas = p;
                break;
            }
        }

        if (tugas == null) {
            lblVUtama.setText("Belum ditugaskan");
            lblVPendamping.setText("-");
            lblVDitugaskan.setText("-");
            lblVCatatan.setText("-");
            return;
        }

        List<String> nama = new dao.PenugasanDAO()
                .getNamaPetugasPerPenugasan()
                .getOrDefault(tugas.getIdPenugasan(), new ArrayList<>());
        lblVUtama.setText(nama.isEmpty() ? "-" : nama.get(0));
        lblVPendamping.setText(nama.size() < 2 ? "-"
                : String.join(", ", nama.subList(1, nama.size())));

        String supervisor = "-";
        for (model.Pengguna p : new dao.PenggunaDAO().getAllPengguna()) {
            if (p.getIdPengguna() == tugas.getSupervisorIdPengguna()) {
                supervisor = p.getNamaLengkap();
                break;
            }
        }
        lblVDitugaskan.setText(supervisor);
        lblVCatatan.setText(tugas.getCatatanPenugasan() == null
                || tugas.getCatatanPenugasan().trim().isEmpty()
                        ? "-" : tugas.getCatatanPenugasan());
    }

    private void muatProgres() {
        List<ProgresPenanganan> daftar = new ArrayList<>();
        for (Penugasan p : new dao.PenugasanDAO().getAllPenugasan()) {
            if (p.getLaporanIdLaporan() == laporan.getIdLaporan()) {
                daftar.addAll(new dao.ProgresPenangananDAO()
                        .getAllProgres(p.getIdPenugasan()));
            }
        }
        modelProgres.setData(daftar);
        if (daftar.isEmpty()) {
            lblJudulProgres.setText("Riwayat Progres  -  belum ada progres "
                    + "yang dicatat");
        }
    }

