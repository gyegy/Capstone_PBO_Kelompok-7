    private void muatData() {
        Penugasan tugas = null;
        for (Penugasan p : new PenugasanDAO().getAllPenugasan()) {
            if (p.getIdPenugasan() == idPenugasan) {
                tugas = p;
                break;
            }
        }

        lblJudul.setText("Riwayat Progres Penugasan " + ViewUtil.idTugas(idPenugasan));

        if (tugas != null) {
            LaporanKerusakan l = ViewUtil.petaLaporan().get(tugas.getLaporanIdLaporan());
            Fasilitas f = l == null ? null
                    : ViewUtil.petaFasilitas().get(l.getFasilitasIdFasilitas());
            String petugas = SupervisorUtil.namaPetugas(tugas,
                    SupervisorUtil.petugasPerPenugasan(),
                    SupervisorUtil.namaPengguna(), true);

            lblSub.setText((f == null ? "-" : f.getNamaFasilitas()) + " \u00b7 " + petugas);
        }

        List<ProgresPenanganan> riwayat = new ProgresPenangananDAO().getAllProgres(idPenugasan);
        DefaultTableModel model = (DefaultTableModel) tblRiwayat.getModel();
        model.setRowCount(0);

        for (ProgresPenanganan r : riwayat) {
            model.addRow(new Object[] {
                ViewUtil.waktu(r.getWaktuUpdate()),
                r.getStatusProgres(),
                r.getTindakanPenanganan() == null ? "-" : r.getTindakanPenanganan()
            });
        }

        lblInfo.setText(riwayat.isEmpty() ? "Belum ada riwayat progres" : riwayat.size() + " catatan progres");
    }

