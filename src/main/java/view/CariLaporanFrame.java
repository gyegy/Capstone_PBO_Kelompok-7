    // Detail: laporan + fasilitas + petugas penanggung jawab + riwayat progres
    private void btnDetailActionPerformed(java.awt.event.ActionEvent evt) {
        int baris = tblHasil.getSelectedRow();

        if (baris < 0 || baris >= hasil.size()) {
            JOptionPane.showMessageDialog(this,
                    "Pilih laporan pada tabel terlebih dahulu",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        LaporanKerusakan l = hasil.get(baris);
        Fasilitas f = petaFasilitas.get(l.getFasilitasIdFasilitas());
        StringBuilder sb = new StringBuilder();

        sb.append("Detail Laporan L-").append(String.format("%04d", l.getIdLaporan())).append("\n\n");
        sb.append("Fasilitas  : ").append(f == null ? "-" : f.getNamaFasilitas()
                + " (" + f.getJenisFasilitas() + ")").append("\n");
        sb.append("Lokasi     : ").append(f == null ? "-" : f.getLokasi()).append("\n");
        sb.append("Tanggal    : ").append(formatTanggal.format(l.getTanggalLaporan())).append("\n");
        sb.append("Prioritas  : ").append(l.getPrioritas()).append("\n");
        sb.append("Status     : ").append(l.getStatus()).append("\n");
        sb.append("Deskripsi  : ").append(l.getDeskripsiKerusakan()).append("\n");

        Penugasan tugas = null;
        for (Penugasan p : new PenugasanDAO().getAllPenugasan()) {
            if (p.getLaporanIdLaporan() == l.getIdLaporan()) {
                tugas = p;
                break;
            }
        }

        sb.append("\nPetugas Penanggung Jawab\n");
        if (tugas == null) {
            sb.append("  Belum ada penugasan\n");
        } else {
            String namaPetugas = "-";
            String namaSupervisor = "-";
            for (Pengguna u : new PenggunaDAO().getAllPengguna()) {
                if (u.getIdPengguna() == tugas.getIdPengguna()) {
                    namaPetugas = u.getNamaLengkap();
                }
                if (u.getIdPengguna() == tugas.getSupervisorIdPengguna()) {
                    namaSupervisor = u.getNamaLengkap();
                }
            }
            sb.append("  Utama          : ").append(namaPetugas).append("\n");
            sb.append("  Ditugaskan oleh: ").append(namaSupervisor).append("\n");
            sb.append("  Catatan        : ").append(tugas.getCatatanPenugasan() == null
                    ? "-" : tugas.getCatatanPenugasan()).append("\n");

            sb.append("\nRiwayat Progres\n");
            List<ProgresPenanganan> riwayat =
                    new ProgresPenangananDAO().getAllProgres(tugas.getIdPenugasan());
            if (riwayat.isEmpty()) {
                sb.append("  Belum ada progres\n");
            }
            SimpleDateFormat waktu = new SimpleDateFormat("dd MMM yyyy HH:mm",
                    new Locale("id", "ID"));
            for (ProgresPenanganan r : riwayat) {
                sb.append("  ").append(waktu.format(r.getWaktuUpdate()))
                  .append(" | ").append(r.getStatusProgres())
                  .append(" | ").append(r.getTindakanPenanganan() == null
                          ? "-" : r.getTindakanPenanganan()).append("\n");
            }
        }

        JOptionPane.showMessageDialog(this, sb.toString(),
                "Detail Laporan", JOptionPane.PLAIN_MESSAGE);
    }

    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {
        String peran = Sesi.getPeran();

        if ("Petugas".equals(peran)) {
            new PetugasMenuFrame().setVisible(true);
        } else if ("Supervisor".equals(peran)) {
            new DashboardSupervisor().setVisible(true);
        } else {
            new AdminMenuFrame().setVisible(true);
        }
        dispose();
    }


