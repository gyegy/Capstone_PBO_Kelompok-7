    // Isi tabel laporan (Menunggu & belum ditugaskan) dan petugas aktif
    private void muatData() {
        sedangMemuat = true;
        urutanPilih.clear();

        daftarLaporan = SupervisorUtil.laporanMenungguPenugasan();
        daftarPetugas = SupervisorUtil.petugasAktif();
        Map<Integer, Fasilitas> fasilitas = ViewUtil.petaFasilitas();

        DefaultTableModel mLaporan = (DefaultTableModel) tblLaporan.getModel();
        mLaporan.setRowCount(0);
        for (LaporanKerusakan l : daftarLaporan) {
            Fasilitas f = fasilitas.get(l.getFasilitasIdFasilitas());
            mLaporan.addRow(new Object[] {
                ViewUtil.idLaporan(l.getIdLaporan()),
                f == null ? "-" : f.getNamaFasilitas(),
                f == null ? "-" : f.getLokasi(),
                l.getPrioritas()
            });
        }

        DefaultTableModel mPetugas = (DefaultTableModel) tblPetugas.getModel();
        mPetugas.setRowCount(0);
        for (Petugas p : daftarPetugas) {
            mPetugas.addRow(new Object[] {
                Boolean.FALSE, p.getNamaLengkap(),
                p.getSpesialisasi(), p.getShiftKerja(), "-"
            });
        }

        sedangMemuat = false;

        if (daftarLaporan.isEmpty()) {
            lblInfo.setText("Tidak ada laporan menunggu penugasan");
        } else if (daftarPetugas.isEmpty()) {
            lblInfo.setText("Tidak ada petugas aktif");
        } else {
            lblInfo.setText("Status laporan tetap Menunggu sampai Petugas mencatat progres pertama");
        }
    }

    // Catat urutan centang petugas lalu perbarui kolom Peran
    private void aturPilihan(int baris) {
        DefaultTableModel m = (DefaultTableModel) tblPetugas.getModel();
        Integer indeks = baris;

        if (Boolean.TRUE.equals(m.getValueAt(baris, 0))) {
            if (!urutanPilih.contains(indeks)) {
                urutanPilih.add(indeks);
            }
        } else {
            urutanPilih.remove(indeks);
        }
        segarkanPeran();
    }

    private void segarkanPeran() {
        DefaultTableModel m = (DefaultTableModel) tblPetugas.getModel();
        sedangMemuat = true;
        try {
            for (int i = 0; i < m.getRowCount(); i++) {
                String peran = "-";
                if (urutanPilih.contains(i)) {
                    peran = urutanPilih.get(0) == i ? "Utama" : "Pendamping";
                }
                m.setValueAt(peran, i, 4);
            }
        } finally {
            sedangMemuat = false;
        }
    }

    // Ubah petugas terpilih (yang sudah dicentang) menjadi Petugas Utama
    private void btnUtamaActionPerformed(java.awt.event.ActionEvent evt) {
        int baris = tblPetugas.getSelectedRow();

        if (baris < 0 || !urutanPilih.contains(baris)) {
            JOptionPane.showMessageDialog(this,
                    "Pilih baris petugas yang sudah dicentang terlebih dahulu",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        urutanPilih.remove(Integer.valueOf(baris));
        urutanPilih.add(0, baris);
        segarkanPeran();
    }

    private void btnBatalActionPerformed(java.awt.event.ActionEvent evt) {
        txtCatatan.setText("");
        muatData();
    }

    // Simpan ke PENUGASAN + DETAIL_PENUGASAN (satu baris per petugas, Aktif)
    private void btnBuatActionPerformed(java.awt.event.ActionEvent evt) {
        int baris = tblLaporan.getSelectedRow();

        if (daftarLaporan.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tidak ada laporan menunggu penugasan",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        if (daftarPetugas.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Tidak ada petugas aktif",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        if (baris < 0 || baris >= daftarLaporan.size()) {
            JOptionPane.showMessageDialog(this, "Pilih satu laporan terlebih dahulu",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (urutanPilih.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih minimal satu petugas",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String catatan = txtCatatan.getText().trim();
        if (catatan.length() > 150) {
            JOptionPane.showMessageDialog(this, "Catatan melebihi 150 karakter",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        LaporanKerusakan laporan = daftarLaporan.get(baris);
        List<Integer> idPetugas = new ArrayList<>();
        for (Integer indeks : urutanPilih) {
            idPetugas.add(daftarPetugas.get(indeks).getIdPengguna());
        }

        Penugasan p = new Penugasan();
        p.setWaktuPenugasan(java.sql.Date.valueOf(java.time.LocalDate.now()));
        p.setCatatanPenugasan(catatan.isEmpty() ? null : catatan);
        p.setSupervisorIdPengguna(SupervisorUtil.idSupervisor());
        p.setLaporanIdLaporan(laporan.getIdLaporan());
        p.setIdPengguna(idPetugas.get(0)); // Petugas utama

        if (penugasanDAO.tambahPenugasan(p, idPetugas)) {
            JOptionPane.showMessageDialog(this, "Penugasan berhasil dibuat",
                    "Berhasil", JOptionPane.INFORMATION_MESSAGE);
            txtCatatan.setText("");
            muatData();
        } else {
            JOptionPane.showMessageDialog(this, "Penugasan gagal disimpan",
                    "Kesalahan", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {
        new SupervisorMenuFrame().setVisible(true);
        dispose();
    }


