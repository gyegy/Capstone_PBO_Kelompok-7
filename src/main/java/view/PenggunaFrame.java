    // UPDATE (peran tidak dapat diubah)
    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {
        Pengguna p = penggunaTerpilih();
        if (p == null) {
            return;
        }

        PenggunaDialog dialog = new PenggunaDialog(this, true, p);
        dialog.setVisible(true);

        if (dialog.isBerhasil()) {
            muatData(txtCari.getText());
        }
    }

    // Aktif / Nonaktifkan: membalik status_aktif
    private void btnStatusActionPerformed(java.awt.event.ActionEvent evt) {
        Pengguna p = penggunaTerpilih();
        if (p == null) {
            return;
        }

        boolean aktif = "Aktif".equals(p.getStatusAktif());

        if (aktif && String.valueOf(p.getIdPengguna()).equals(Sesi.getIdPengguna())) {
            JOptionPane.showMessageDialog(this,
                    "Akun sendiri tidak dapat dinonaktifkan",
                    "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String aksi = aktif ? "Nonaktifkan" : "Aktifkan";
        int pilih = JOptionPane.showConfirmDialog(this,
                aksi + " pengguna " + p.getNamaLengkap() + "?",
                "Konfirmasi", JOptionPane.YES_NO_OPTION);

        if (pilih != JOptionPane.YES_OPTION) {
            return;
        }

        boolean berhasil = aktif
                ? penggunaDAO.hapusPengguna(p.getIdPengguna())
                : aktifkanKembali(p);

        if (berhasil) {
            JOptionPane.showMessageDialog(this,
                    "Status pengguna berhasil diperbarui");
            muatData(txtCari.getText());
        } else {
            JOptionPane.showMessageDialog(this,
                    "Status pengguna gagal diperbarui",
                    "Kesalahan", JOptionPane.ERROR_MESSAGE);
        }
    }

    // DAO hanya punya "nonaktifkan"; aktifkan lagi lewat updatePengguna
    // (password dikosongkan = password lama dipertahankan)
    private boolean aktifkanKembali(Pengguna p) {
        String data1 = null;
        String data2 = null;

        if (p instanceof Admin) {
            data1 = ((Admin) p).getHakAkses();
        } else if (p instanceof Supervisor) {
            data1 = ((Supervisor) p).getAreaPengawasan();
        } else if (p instanceof Petugas) {
            data1 = ((Petugas) p).getSpesialisasi();
            data2 = ((Petugas) p).getShiftKerja();
        }

        return penggunaDAO.updatePengguna(p.getIdPengguna(),
                p.getNamaLengkap(), p.getUsername(), "", p.getEmail(),
                p.getNoTelepon(), "Aktif", data1, data2);
    }

    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {
        new AdminMenuFrame().setVisible(true);
        dispose();
    }


