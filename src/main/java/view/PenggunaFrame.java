    // READ: tampilkan daftar pengguna (semua atau hasil pencarian)
    private void muatData(String kataKunci) {
        if (kataKunci == null || kataKunci.trim().isEmpty()) {
            daftar = penggunaDAO.getAllPengguna();
        } else {
            daftar = penggunaDAO.searchPengguna(kataKunci.trim());
        }

        DefaultTableModel model = (DefaultTableModel) tblPengguna.getModel();
        model.setRowCount(0);

        for (Pengguna p : daftar) {
            model.addRow(new Object[] {
                String.format("P%03d", p.getIdPengguna()),
                p.getNamaLengkap(),
                p.getUsername(),
                p.getPeran(),
                p.getStatusAktif(),
                dataKhusus(p)
            });
        }

        lblInfo.setText("Menampilkan " + daftar.size() + " pengguna");
    }

    private String dataKhusus(Pengguna p) {
        if (p instanceof Admin) {
            return "Hak akses: " + nilai(((Admin) p).getHakAkses());
        }
        if (p instanceof Supervisor) {
            return "Area: " + nilai(((Supervisor) p).getAreaPengawasan());
        }
        if (p instanceof Petugas) {
            Petugas t = (Petugas) p;
            return t.getSpesialisasi() + " \u00b7 Shift " + t.getShiftKerja();
        }
        return "-";
    }

    private String nilai(String s) {
        return (s == null || s.trim().isEmpty()) ? "-" : s;
    }

    // mengambil pengguna yang dipilih di tabel (null jika belum dipilih)
    private Pengguna penggunaTerpilih() {
        int baris = tblPengguna.getSelectedRow();

        if (baris < 0 || baris >= daftar.size()) {
            JOptionPane.showMessageDialog(this,
                    "Pilih pengguna pada tabel terlebih dahulu",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return null;
        }
        return daftar.get(baris);
    }

