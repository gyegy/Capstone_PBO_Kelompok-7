    private void muatData() {
        daftar = new PenugasanDAO().getAllPenugasan();

        Map<Integer, LaporanKerusakan> laporan = ViewUtil.petaLaporan();
        Map<Integer, Fasilitas> fasilitas = ViewUtil.petaFasilitas();
        Map<Integer, List<Integer>> petugas = SupervisorUtil.petugasPerPenugasan();
        Map<Integer, String> nama = SupervisorUtil.namaPengguna();

        DefaultTableModel model = (DefaultTableModel) tblPenugasan.getModel();
        model.setRowCount(0);

        for (Penugasan p : daftar) {
            LaporanKerusakan l = laporan.get(p.getLaporanIdLaporan());
            Fasilitas f = l == null ? null : fasilitas.get(l.getFasilitasIdFasilitas());
            ProgresPenanganan r = SupervisorUtil.progresTerakhir(p.getIdPenugasan());

            model.addRow(new Object[] {
                ViewUtil.idTugas(p.getIdPenugasan()),
                ViewUtil.tanggal(p.getWaktuPenugasan()),
                SupervisorUtil.namaPetugas(p, petugas, nama, false),
                f == null ? "-" : f.getNamaFasilitas(),
                l == null ? "-" : l.getStatus(),
                r == null ? "-" : r.getStatusProgres()
            });
        }

        lblInfo.setText(daftar.isEmpty()
                ? "Belum ada penugasan"
                : "Total " + daftar.size() + " penugasan. Pilih baris lalu klik Lihat Riwayat.");
    }

    private void btnRiwayatActionPerformed(java.awt.event.ActionEvent evt) {
        int baris = tblPenugasan.getSelectedRow();

        if (baris < 0 || baris >= daftar.size()) {
            JOptionPane.showMessageDialog(this,
                    "Pilih penugasan pada tabel terlebih dahulu",
                    "Informasi", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        new RiwayatPenugasanFrame(daftar.get(baris).getIdPenugasan()).setVisible(true);
        dispose();
    }

    private void btnKembaliActionPerformed(java.awt.event.ActionEvent evt) {
        new SupervisorMenuFrame().setVisible(true);
        dispose();
    }


