    private final LaporanTableModel modelTabel
            = new LaporanTableModel(LaporanTableModel.Mode.SAYA);
    private final Map<Integer, String> namaFasilitas = new HashMap<>();
    private final List<LaporanKerusakan> dataSaya = new ArrayList<>();
    private boolean tabelSiap;

    private void siapkanTabel() {
        tabelLaporan.setModel(modelTabel);
        view.util.UiKit.siapkanTabel(tabelLaporan);
        tabelLaporan.setRowHeight(48);

        int[] lebar = {90, 130, 250, 120, 130, 120};
        for (int i = 0; i < lebar.length; i++) {
            tabelLaporan.getColumnModel().getColumn(i)
                    .setPreferredWidth(lebar[i]);
        }
        tabelLaporan.getColumnModel().getColumn(0)
                .setCellRenderer(new RendererTabel.Id());
        tabelLaporan.getColumnModel().getColumn(1)
                .setCellRenderer(new RendererTabel.TeksRedup());
        tabelLaporan.getColumnModel().getColumn(2)
                .setCellRenderer(new RendererTabel.Utama());
        tabelLaporan.getColumnModel().getColumn(3)
                .setCellRenderer(new RendererTabel.Lencana());
        tabelLaporan.getColumnModel().getColumn(4)
                .setCellRenderer(new RendererTabel.Lencana());
        tabelLaporan.getColumnModel().getColumn(5)
                .setCellRenderer(new RendererTabel.AksiDinamis());

        tabelLaporan.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent e) {
                int baris = tabelLaporan.rowAtPoint(e.getPoint());
                int kolom = tabelLaporan.columnAtPoint(e.getPoint());
                if (baris < 0 || kolom != 5
                        || baris >= modelTabel.getRowCount()) {
                    return;
                }
                bukaForm(modelTabel.get(baris));
            }
        });

        tombolCatat.addActionListener(e -> bukaForm(null));
    }

    @Override
    public String judul() {
        return "Laporan Kerusakan";
    }

    @Override
    public void muatData() {
        if (!tabelSiap) {
            tabelSiap = true;
            siapkanTabel();
        }

        namaFasilitas.clear();
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            namaFasilitas.put(f.getIdFasilitas(), f.getNamaFasilitas());
        }

        dataSaya.clear();
        List<String> nama = new ArrayList<>();
        for (LaporanKerusakan l
                : new dao.LaporanKerusakanDAO().getAllLaporan()) {
            if (l.getAdminIdPengguna() == view.util.Session.id()) {
                dataSaya.add(l);
                nama.add(namaFasilitas.getOrDefault(
                        l.getFasilitasIdFasilitas(), "-"));
            }
        }
        modelTabel.setData(dataSaya, nama, null);
        lblCatatan.setText("Menampilkan " + dataSaya.size()
                + " laporan yang Anda catat  -  klik Ubah untuk laporan "
                + "berstatus Menunggu");
    }

    private void bukaForm(LaporanKerusakan laporan) {
        java.awt.Window jendela
                = javax.swing.SwingUtilities.getWindowAncestor(this);
        if (jendela instanceof MainFrame) {
            ((MainFrame) jendela).bukaForm(
                    laporan == null ? "Catat Laporan" : "Ubah Laporan",
                    new FormLaporan(laporan));
        }
    }

    @Override
    public void sesuaikanUkuran(int lebar, int tinggi) {
        int isi = Math.max(600, lebar - 68);
        tombolCatat.setBounds(34 + isi - 236, 160, 236, 38);
        int tinggiKartu = Math.max(240, tinggi - 280);
        panelTabel.setBounds(34, 216, isi, tinggiKartu);
        scrollLaporan.setBounds(22, 18, isi - 44, tinggiKartu - 36);
        tabelLaporan.setBounds(0, 0, isi - 44, tinggiKartu - 36);
        lblCatatan.setBounds(34, 216 + tinggiKartu + 12, 800, 18);
    }
