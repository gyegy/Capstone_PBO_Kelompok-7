    private boolean tabelSiap;

    private void siapkanTabel() {
        for (javax.swing.JComboBox<String> combo
                : new javax.swing.JComboBox[]{cmbStatus, cmbPrioritas,
                    cmbPetugas}) {
            view.util.UiKit.siapkanCombo(combo);
        }
        tabelHasil.setModel(modelTabel);
        view.util.UiKit.siapkanTabel(tabelHasil);
        tabelHasil.setRowHeight(48);

        int[] lebar = {90, 120, 190, 110, 110, 200, 100};
        for (int i = 0; i < lebar.length; i++) {
            tabelHasil.getColumnModel().getColumn(i)
                    .setPreferredWidth(lebar[i]);
        }
        tabelHasil.getColumnModel().getColumn(0)
                .setCellRenderer(new RendererTabel.Id());
        tabelHasil.getColumnModel().getColumn(1)
                .setCellRenderer(new RendererTabel.TeksRedup());
        tabelHasil.getColumnModel().getColumn(2)
                .setCellRenderer(new RendererTabel.Utama());
        tabelHasil.getColumnModel().getColumn(3)
                .setCellRenderer(new RendererTabel.Lencana());
        tabelHasil.getColumnModel().getColumn(4)
                .setCellRenderer(new RendererTabel.Lencana());
        tabelHasil.getColumnModel().getColumn(5)
                .setCellRenderer(new RendererTabel.TeksRedup());
        tabelHasil.getColumnModel().getColumn(6)
                .setCellRenderer(new RendererTabel.AksiDinamis());

        // Petugas hanya melihat laporan pada penugasannya sendiri, sehingga
        // kolom dan saringan petugas disembunyikan.
        if (view.util.Session.petugas()) {
            cmbPetugas.setVisible(false);
            lblPetugas.setVisible(false);
            javax.swing.table.TableColumn kolom
                    = tabelHasil.getColumnModel().getColumn(5);
            kolom.setMinWidth(0);
            kolom.setMaxWidth(0);
            kolom.setPreferredWidth(0);
            lblSubJudul.setText("Kosongkan kriteria yang tidak diperlukan  - "
                    + "hanya laporan pada penugasan Anda");
        }

        tabelHasil.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent e) {
                int baris = tabelHasil.rowAtPoint(e.getPoint());
                int kolom = tabelHasil.columnAtPoint(e.getPoint());
                if (baris < 0 || baris >= modelTabel.getRowCount()) {
                    return;
                }
                int kolomAksi = modelTabel.getColumnCount() - 1;
                if (kolom == kolomAksi) {
                    bukaDetail(modelTabel.get(baris));
                }
            }
        });

        tombolCari.addActionListener(e -> terapkan());
        tombolReset.addActionListener(e -> reset());
    }

    @Override
    public String judul() {
        return "Cari Laporan";
    }

    @Override
    public void muatData() {
        if (!tabelSiap) {
            tabelSiap = true;
            siapkanTabel();
        }

        namaFasilitas.clear();
        for (Fasilitas f : new dao.FasilitasDAO().getAllFasilitas()) {
            namaFasilitas.put(f.getIdFasilitas(), f.getNamaFasilitas());
        }

        petugasPerLaporan.clear();
        petugasPerLaporan.putAll(
                new dao.PenugasanDAO().getNamaPetugasPerLaporan());

        dataLengkap = new dao.LaporanKerusakanDAO().getAllLaporan();
        isiPilihanPetugas();
        terapkan();
    }

    private void isiPilihanPetugas() {
        if (view.util.Session.petugas()) {
            return;
        }
        List<String> isi = new ArrayList<>();
        isi.add("Semua");
        for (Pengguna p : new dao.PenggunaDAO().getAllPengguna()) {
            if ("Petugas".equalsIgnoreCase(p.getPeran())) {
                isi.add(p.getNamaLengkap());
            }
        }
        cmbPetugas.setModel(new javax.swing.DefaultComboBoxModel<>(
                isi.toArray(new String[0])));
    }

    private void reset() {
        txtId.setText("");
        txtDari.setText("");
        txtSampai.setText("");
        txtFasilitas.setText("");
        cmbStatus.setSelectedIndex(0);
        cmbPrioritas.setSelectedIndex(0);
        if (cmbPetugas.isVisible() && cmbPetugas.getItemCount() > 0) {
            cmbPetugas.setSelectedIndex(0);
        }
        terapkan();
    }

    private void terapkan() {
        String kunciId = txtId.getText().trim().toLowerCase();
        if (kunciId.startsWith("l-")) {
            kunciId = kunciId.substring(2);
        }
        String kunciFasilitas = txtFasilitas.getText().trim().toLowerCase();
        String status = String.valueOf(cmbStatus.getSelectedItem());
        String prioritas = String.valueOf(cmbPrioritas.getSelectedItem());
        String petugas = cmbPetugas.isVisible()
                ? String.valueOf(cmbPetugas.getSelectedItem()) : "Semua";
        Date dari = urai(txtDari.getText());
        Date sampai = urai(txtSampai.getText());

        List<LaporanKerusakan> hasil = new ArrayList<>();
        List<String> namaBaris = new ArrayList<>();
        List<String> petugasBaris = new ArrayList<>();

        for (LaporanKerusakan l : dataLengkap) {
            String nama = namaFasilitas.getOrDefault(
                    l.getFasilitasIdFasilitas(), "-");
            List<String> daftarPetugas = petugasPerLaporan.getOrDefault(
                    l.getIdLaporan(), new ArrayList<>());
            String gabungPetugas = String.join(", ", daftarPetugas);

            if (!kunciId.isEmpty()
                    && !String.valueOf(l.getIdLaporan()).contains(kunciId)) {
                continue;
            }
            if (!kunciFasilitas.isEmpty()
                    && !nama.toLowerCase().contains(kunciFasilitas)) {
                continue;
            }
            if (!"Semua".equals(status) && !status.equals(l.getStatus())) {
                continue;
            }
            if (!"Semua".equals(prioritas)
                    && !prioritas.equals(l.getPrioritas())) {
                continue;
            }
            if (!"Semua".equals(petugas)
                    && !gabungPetugas.contains(petugas)) {
                continue;
            }
            if (view.util.Session.petugas()
                    && !gabungPetugas.contains(view.util.Session.nama())) {
                continue;
            }
            if (dari != null && l.getTanggalLaporan() != null
                    && l.getTanggalLaporan().before(dari)) {
                continue;
            }
            if (sampai != null && l.getTanggalLaporan() != null
                    && l.getTanggalLaporan().after(sampai)) {
                continue;
            }

            hasil.add(l);
            namaBaris.add(nama);
            petugasBaris.add(gabungPetugas.isEmpty() ? "-" : gabungPetugas);
        }

        modelTabel.setData(hasil, namaBaris, petugasBaris);
        lblCatatan.setText(hasil.isEmpty()
                ? "Tidak ada laporan yang sesuai kriteria pencarian"
                : "Menampilkan " + hasil.size() + " dari " + dataLengkap.size()
                  + " laporan  -  klik Detail untuk melihat riwayat progres");
    }

    /** Mengurai teks tanggal; mengembalikan null bila kosong atau salah. */
    private Date urai(String teks) {
        String bersih = teks == null ? "" : teks.trim();
        if (bersih.isEmpty()) {
            return null;
        }
        for (String pola : POLA_TANGGAL) {
            try {
                SimpleDateFormat format
                        = new SimpleDateFormat(pola, new Locale("id", "ID"));
                format.setLenient(false);
                return format.parse(bersih);
            } catch (ParseException e) {
                // Coba pola berikutnya.
            }
        }
        lblCatatan.setText("Format tanggal belum dikenali: " + bersih
                + "  -  gunakan contoh 01 Okt 2026 atau 01/10/2026");
        return null;
    }

    private void bukaDetail(LaporanKerusakan laporan) {
        java.awt.Window jendela
                = javax.swing.SwingUtilities.getWindowAncestor(this);
        if (jendela instanceof MainFrame) {
            ((MainFrame) jendela).bukaForm(
                    "Detail Laporan " + view.util.FormatUi.idLaporan(
                            laporan.getIdLaporan()),
                    new DetailLaporanView(laporan));
        }
    }

