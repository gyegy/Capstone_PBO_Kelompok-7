    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {
        boolean tambah = (dataLama == null);

        String nama = txtNama.getText().trim();
        Object jenisPilih = cmbJenis.getEditor().getItem();
        String jenis = jenisPilih == null ? "" : jenisPilih.toString().trim();
        String lokasi = txtLokasi.getText().trim();
        String kondisi = (String) cmbKondisi.getSelectedItem();
        String keterangan = txtKeterangan.getText().trim();

        // validasi: data terisi dan sesuai batas panjang kolom
        if (nama.isEmpty() || jenis.isEmpty() || lokasi.isEmpty()
                || nama.length() > 30 || jenis.length() > 30
                || lokasi.length() > 50 || keterangan.length() > 60) {
            peringatan("Data tidak lengkap atau melebihi batas");
            return;
        }

        Fasilitas f = new Fasilitas();
        f.setNamaFasilitas(nama);
        f.setJenisFasilitas(jenis);
        f.setLokasi(lokasi);
        f.setKondisi(kondisi);
        f.setKeterangan(keterangan.isEmpty() ? null : keterangan);

        boolean ok;
        if (tambah) {
            // ADMIN_id_pengguna = admin yang sedang login
            f.setAdminIdPengguna(Integer.parseInt(Sesi.getIdPengguna()));
            ok = fasilitasDAO.tambahFasilitas(f);
        } else {
            f.setIdFasilitas(dataLama.getIdFasilitas());
            f.setAdminIdPengguna(dataLama.getAdminIdPengguna());
            ok = fasilitasDAO.updateFasilitas(f);
        }

        if (ok) {
            JOptionPane.showMessageDialog(this, tambah
                    ? "Fasilitas berhasil ditambahkan"
                    : "Data fasilitas berhasil diperbarui");
            berhasil = true;
            dispose();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Data fasilitas gagal disimpan. Periksa koneksi database.",
                    "Kesalahan", JOptionPane.ERROR_MESSAGE);
        }
    }


