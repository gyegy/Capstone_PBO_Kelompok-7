    private void muatData() {
        Fasilitas f = ViewUtil.petaFasilitas().get(idFasilitas);

        List<LaporanKerusakan> daftar = new ArrayList<>();
        for (LaporanKerusakan l : SupervisorUtil.laporanPeriode(dari, sampai)) {
            if (l.getFasilitasIdFasilitas() == idFasilitas) {
                daftar.add(l);
            }
        }
        // Terbaru di atas
        daftar.sort((a, b) -> {
            int c = b.getTanggalLaporan().compareTo(a.getTanggalLaporan());
            return c != 0 ? c : Integer.compare(b.getIdLaporan(), a.getIdLaporan());
        });

        Map<Integer, Penugasan> tugas = SupervisorUtil.penugasanPerLaporan();
        DefaultTableModel model = (DefaultTableModel) tblRiwayat.getModel();
        model.setRowCount(0);

        for (LaporanKerusakan l : daftar) {
            Penugasan p = tugas.get(l.getIdLaporan());
            ProgresPenanganan r = p == null ? null
                    : SupervisorUtil.progresTerakhir(p.getIdPenugasan());

            model.addRow(new Object[] {
                ViewUtil.idLaporan(l.getIdLaporan()),
                ViewUtil.tanggal(l.getTanggalLaporan()),
                l.getDeskripsiKerusakan(),
                l.getStatus(),
                (r == null || r.getTindakanPenanganan() == null) ? "-" : r.getTindakanPenanganan()
            });
        }

        lblJudul.setText("Riwayat Gangguan: " + (f == null ? "-" : f.getNamaFasilitas()));
        lblSub.setText((f == null ? "-" : f.getLokasi()) + " \u00b7 "
                + daftar.size() + " laporan pada periode terpilih");
        lblInfo.setText(daftar.isEmpty() ? "Belum ada gangguan pada periode ini" : " ");
    }

